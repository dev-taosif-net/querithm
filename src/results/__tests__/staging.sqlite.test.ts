// Phase D1: grid editing over SQLite's dynamically typed result columns (every column carries hidden siblings).
import { describe, expect, it } from "vitest";
import type { ResultEditInfo } from "../../ipc/contract";
import { ArrowResultSet } from "../model";
import { GridStaging } from "../staging";
import { dynamicColumn, makeBatch } from "./fixtures";

/** SELECT * FROM t on (id INTEGER PRIMARY KEY, v): both columns dynamic, as the sidecar sends them. */
function sqliteResult() {
  const rs = new ArrowResultSet(0);
  rs.append(makeBatch([...dynamicColumn("id", [[1, "1"], [1, "2"]], 0, "INTEGER"), ...dynamicColumn("v", [[1, "1"], [3, "a"]], 1, "")]));
  rs.finish(false);
  return rs;
}

const edit: ResultEditInfo = {
  editable: true, reason: null, objectId: 7, schema: "main", table: "t", keyColumns: ["id"], keyOrdinals: [0], tokenKind: null, tokenColumn: null,
  insertBlockedReason: null, concurrencyNote: "SQLite keeps no row version.",
  columns: [
    { ordinal: 0, column: "id", type: "INTEGER", nullable: false, hasDefault: true, generated: true, locked: true, lockReason: "identity values are generated by the server", comparable: true, key: true },
    { ordinal: 1, column: "v", type: "", nullable: true, hasDefault: false, generated: false, locked: false, lockReason: null, comparable: false, key: false },
  ],
};

describe("GridStaging over SQLite's dynamic columns", () => {
  it("an untyped column's cells can be edited and staged", () => {
    const rs = sqliteResult();
    const s = new GridStaging(edit, rs, "sqlite");
    expect(s.lockReason({ kind: "existing", row: 0 }, 1)).toBeNull();
    expect(s.lockReason({ kind: "existing", row: 0 }, 0)).toContain("identity");
  });
});
