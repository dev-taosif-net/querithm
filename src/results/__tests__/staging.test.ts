import { describe, expect, it } from "vitest";
import type { ResultEditInfo } from "../../ipc/contract";
import { CHANGED_ON_SERVER, GridStaging, gridValue, pendingIn, stagingKey, stagings, type StagingSource } from "../staging";

// orders(id PK identity, name NOT NULL, qty NULL, notes NULL truncatable, total computed); a fake Arrow source.
function source(rows: (string | null)[][], truncated: Set<string> = new Set()): StagingSource {
  return {
    rowCount: rows.length,
    columns: [
      { ordinal: 0, name: "id", typeName: "int" },
      { ordinal: 1, name: "name", typeName: "nvarchar" },
      { ordinal: 2, name: "qty", typeName: "int" },
      { ordinal: 3, name: "notes", typeName: "nvarchar" },
      { ordinal: 4, name: "total", typeName: "int" },
    ],
    textPhysical: (r, c) => rows[r][c],
    isTruncatedPhysical: (r, c) => truncated.has(`${r}:${c}`),
  };
}

function edit(overrides: Partial<ResultEditInfo> = {}): ResultEditInfo {
  return {
    editable: true, reason: null, objectId: 1, schema: "dbo", table: "orders", keyColumns: ["id"], keyOrdinals: [0],
    tokenKind: "rowversion", tokenColumn: "rv", insertBlockedReason: null, concurrencyNote: "note",
    columns: [
      { ordinal: 0, column: "id", type: "int", nullable: false, hasDefault: true, generated: true, locked: true, lockReason: "identity values are generated by the server", comparable: true, key: true },
      { ordinal: 1, column: "name", type: "nvarchar(5)", nullable: false, hasDefault: false, generated: false, locked: false, lockReason: null, comparable: true, key: false },
      { ordinal: 2, column: "qty", type: "int", nullable: true, hasDefault: false, generated: false, locked: false, lockReason: null, comparable: true, key: false },
      { ordinal: 3, column: "notes", type: "nvarchar(max)", nullable: true, hasDefault: false, generated: false, locked: false, lockReason: null, comparable: false, key: false },
      { ordinal: 4, column: "total", type: "int", nullable: true, hasDefault: false, generated: true, locked: true, lockReason: "computed column", comparable: true, key: false },
    ],
    ...overrides,
  };
}

const rows = () => [
  ["1", "one", "1", "a", "10"],
  ["2", "two", null, "b", "20"],
  ["3", "three", "3", "long…", "30"],
];

const ex = (row: number) => ({ kind: "existing" as const, row });
const ins = (index: number) => ({ kind: "inserted" as const, index });

describe("GridStaging", () => {
  it("stages a cell, shows it over the original and drops it when set back", () => {
    const s = new GridStaging(edit(), source(rows()));
    expect(s.setCell(ex(0), 1, { value: "uno" })).toBe(true);
    expect(s.cell(ex(0), 1)).toMatchObject({ value: "uno", staged: true });
    expect(s.original(0, 1)).toBe("one");
    expect(s.counts).toEqual({ updates: 1, inserts: 0, deletes: 0 });
    s.setCell(ex(0), 1, { value: "one" });
    expect(s.hasChanges).toBe(false);
  });

  it("stages a truncated value when the edit carries the full value (cell viewer), but never a locked column", () => {
    const s = new GridStaging(edit(), source(rows(), new Set(["2:3"])));
    expect(s.setCell(ex(2), 3, { value: "inline" })).toBe(false);
    expect(s.setCell(ex(2), 3, { value: "the full text" }, true)).toBe(true);
    expect(s.cell(ex(2), 3)).toMatchObject({ value: "the full text", staged: true });
    expect(s.setCell(ex(2), 0, { value: "9" }, true)).toBe(false);
    // a shortened key still blocks the row, full value or not
    const k = new GridStaging(edit(), source(rows(), new Set(["1:0"])));
    expect(k.setCell(ex(1), 1, { value: "x" }, true)).toBe(false);
  });

  it("refuses locked columns, truncated values and rows marked for deletion", () => {
    const s = new GridStaging(edit(), source(rows(), new Set(["2:3"])));
    expect(s.lockReason(ex(0), 0)).toBe("identity values are generated by the server");
    expect(s.lockReason(ex(0), 4)).toBe("computed column");
    expect(s.lockReason(ex(2), 3)).toMatch(/shortened in the grid/);
    expect(s.setCell(ex(0), 4, { value: "1" })).toBe(false);
    s.toggleDelete([ex(1)]);
    expect(s.lockReason(ex(1), 1)).toBe("The row is marked for deletion");
  });

  it("read-only result sets explain why", () => {
    const s = new GridStaging(edit({ editable: false, reason: "Read-only: dbo.v is a view" }), source(rows()));
    expect(s.lockReason(ex(0), 1)).toBe("Read-only: dbo.v is a view");
  });

  it("validates values per cell: NULL into NOT NULL, bad numbers, too-long text", () => {
    const s = new GridStaging(edit(), source(rows()));
    s.setCells([
      { ref: ex(0), ordinal: 1, cell: { value: null } },
      { ref: ex(1), ordinal: 2, cell: { value: "12x" } },
      { ref: ex(2), ordinal: 1, cell: { value: "toolong" } },
    ]);
    expect(s.errorFor(ex(0), 1)).toBe("name does not allow NULL");
    expect(s.errorFor(ex(1), 2)).toBe("Not a whole number (int)");
    expect(s.errorFor(ex(2), 1)).toBe("Longer than 5 characters");
    expect(s.problems()).toHaveLength(3);
    s.setCell(ex(1), 2, { value: "12" });
    expect(s.errorFor(ex(1), 2)).toBeUndefined();
  });

  it("undo and redo restore whole steps (a paste is one step)", () => {
    const s = new GridStaging(edit(), source(rows()));
    s.setCells([
      { ref: ex(0), ordinal: 1, cell: { value: "a" } },
      { ref: ex(1), ordinal: 1, cell: { value: "b" } },
    ]);
    s.toggleDelete([ex(2)]);
    expect(s.counts).toEqual({ updates: 2, inserts: 0, deletes: 1 });
    s.undo();
    expect(s.counts).toEqual({ updates: 2, inserts: 0, deletes: 0 });
    s.undo();
    expect(s.hasChanges).toBe(false);
    s.redo();
    expect(s.cell(ex(1), 1).value).toBe("b");
    expect(s.canRedo).toBe(true);
    s.setCell(ex(0), 2, { value: "5" });
    expect(s.canRedo).toBe(false);
  });

  it("new rows: defaults, required values, removal", () => {
    const s = new GridStaging(edit(), source(rows()));
    const i = s.addRow();
    expect(i).toBe(0);
    expect(s.cell(ins(0), 0)).toMatchObject({ isDefault: true }); // identity
    expect(s.lockReason(ins(0), 0)).toBe("Generated by the server on insert");
    expect(s.lockReason(ins(0), 1)).toBeNull();
    expect(s.problems()).toEqual(["New row 1: name needs a value"]);
    s.setCell(ins(0), 1, { value: "new" });
    expect(s.problems()).toEqual([]);
    s.toggleDelete([ins(0)]);
    expect(s.inserted).toHaveLength(0);
  });

  it("insert is unavailable when a required column is missing from the result", () => {
    const s = new GridStaging(edit({ insertBlockedReason: "Inserting needs NOT NULL column x" }), source(rows()));
    expect(s.canInsert).toBe(false);
    expect(s.addRow()).toBe(-1);
  });

  it("asks for tokens of edited and deleted rows with the values the server must still have", () => {
    const s = new GridStaging(edit(), source(rows()));
    s.setCell(ex(0), 1, { value: "uno" });
    s.setCell(ex(0), 3, { value: "note" }); // not comparable: not expected
    s.toggleDelete([ex(1)]);
    const need = s.rowsNeedingTokens();
    expect(need).toEqual([
      { row: 0, expect: { name: { isNull: false, useDefault: false, text: "one" } } },
      { row: 1, expect: { id: gridValue({ value: "2" }), name: gridValue({ value: "two" }), qty: gridValue({ value: null }), total: gridValue({ value: "20" }) } },
    ]);
    s.setTokens([0, 1], ["0x01", null]);
    expect(s.tokens.get(0)).toBe("0x01");
    expect(s.conflicted.get(1)).toBe(CHANGED_ON_SERVER);
    expect(s.rowsNeedingTokens()).toEqual([]);
  });

  it("builds the patch from keys, tokens, original and staged values", () => {
    const s = new GridStaging(edit(), source(rows()));
    s.setCell(ex(1), 2, { value: "7" });
    s.toggleDelete([ex(2)]);
    s.addRow();
    s.setCell(ins(0), 1, { value: "new" });
    s.setTokens([1, 2], ["0x02", "0x03"]);
    const p = s.buildPatch("sid", "eid", 0);
    expect(p.updates).toEqual([{ rowIndex: 1, key: [gridValue({ value: "2" })], token: "0x02", changes: { qty: gridValue({ value: "7" }) }, original: { qty: gridValue({ value: null }) } }]);
    expect(p.deletes[0]).toMatchObject({ rowIndex: 2, key: [gridValue({ value: "3" })], token: "0x03" });
    expect(p.inserts).toEqual([{ tempIndex: 0, values: { name: gridValue({ value: "new" }) } }]);
    expect(p.forceOverwriteConflicts).toBe(false);
  });

  it("commit makes written values the rows' values and new rows existing rows", () => {
    const s = new GridStaging(edit(), source(rows()));
    s.setCell(ex(0), 1, { value: "uno" });
    s.toggleDelete([ex(1)]);
    s.addRow();
    s.setCell(ins(0), 1, { value: "four" });
    s.setTokens([0, 1], ["0x01", "0x02"]);
    const p = s.buildPatch("sid", "eid", 0);
    s.commit(p, { ok: true, appliedUpdates: 1, appliedInserts: 1, appliedDeletes: 1, insertedKeys: { "0": [gridValue({ value: "4" })] } });
    expect(s.hasChanges).toBe(false);
    expect(s.original(0, 1)).toBe("uno");
    expect(s.tokens.has(0)).toBe(false); // new version: re-read before the next edit
    expect(s.appliedDeleted.has(1)).toBe(true);
    expect(s.lockReason(ex(1), 1)).toBe("This row was deleted");
    expect(s.baseRows).toBe(4);
    expect(s.cell(ex(3), 0)).toMatchObject({ value: "4", unknown: false });
    expect(s.cell(ex(3), 2)).toMatchObject({ value: null, unknown: true }); // server default, not known to the grid
    expect(s.keyOf(3)).toEqual([gridValue({ value: "4" })]);
    expect(s.canUndo).toBe(false);
  });

  it("commit applies what the patch carried; what was staged while it was in flight stays staged (W2)", () => {
    const s = new GridStaging(edit(), source(rows()));
    s.setCell(ex(0), 1, { value: "uno" });
    s.setCell(ex(1), 2, { value: "7" });
    s.addRow();
    s.setCell(ins(0), 1, { value: "four" });
    s.toggleDelete([ex(2)]);
    s.setTokens([0, 1, 2], ["0x01", "0x02", "0x03"]);
    const p = s.buildPatch("sid", "eid", 0);
    // While the patch is in flight:
    s.setCell(ex(0), 1, { value: "eins" }); // a newer value of a cell being written
    s.setCell(ex(1), 3, { value: "note" }); // another cell of a row being written
    s.setCell(ins(0), 2, { value: "5" }); // the new row being written, edited
    s.addRow();
    s.setCell(ins(1), 1, { value: "five" }); // a new row never sent
    s.commit(p, { ok: true, appliedUpdates: 2, appliedInserts: 1, appliedDeletes: 1, insertedKeys: { "0": [gridValue({ value: "4" })] } });
    expect(s.original(0, 1)).toBe("uno"); // what the server holds
    expect(s.cell(ex(0), 1)).toMatchObject({ value: "eins", staged: true });
    expect(s.original(1, 2)).toBe("7");
    expect(s.cell(ex(1), 2).staged).toBe(false);
    expect(s.cell(ex(1), 3)).toMatchObject({ value: "note", staged: true });
    expect(s.appliedDeleted.has(2)).toBe(true);
    expect(s.baseRows).toBe(4); // the sent row became row 3
    expect(s.original(3, 1)).toBe("four");
    expect(s.cell(ex(3), 2)).toMatchObject({ value: "5", staged: true }); // its later edit stays, on the row it became
    expect(s.inserted).toHaveLength(1);
    expect(s.cell(ins(0), 1)).toMatchObject({ value: "five", staged: true }); // the row never sent stays new
    expect(s.counts).toEqual({ updates: 3, inserts: 1, deletes: 0 });
  });

  it("dropRows removes edits of conflicting rows only", () => {
    const s = new GridStaging(edit(), source(rows()));
    s.setCell(ex(0), 1, { value: "a" });
    s.setCell(ex(1), 1, { value: "b" });
    s.dropRows([1]);
    expect([...s.edits.keys()]).toEqual([0]);
  });

  it("pendingIn finds staged changes of a tab's executions", () => {
    stagings.clear();
    const s = new GridStaging(edit(), source(rows()));
    stagings.set(stagingKey("E1", 0), s);
    expect(pendingIn(["E1"])).toEqual([]);
    s.setCell(ex(0), 1, { value: "x" });
    expect(pendingIn(["E1", "E2"])).toEqual([s]);
    expect(pendingIn(["E2"])).toEqual([]);
    stagings.clear();
  });

  it("DEFAULT is refused on existing rows", () => {
    const s = new GridStaging(edit(), source(rows()));
    s.setCell(ex(0), 2, { value: null, isDefault: true });
    expect(s.errorFor(ex(0), 2)).toBe("DEFAULT is only allowed on new rows");
  });

  it("buildPatch with force=true sets forceOverwriteConflicts and preserves composite keys", () => {
    const compEdit = edit({
      keyColumns: ["id", "name"],
      keyOrdinals: [0, 1],
    });
    const s = new GridStaging(compEdit, source(rows()));
    s.setCell(ex(0), 2, { value: "99" });
    s.setTokens([0], ["0x01"]);
    const p = s.buildPatch("sid", "eid", 0, true);
    expect(p.forceOverwriteConflicts).toBe(true);
    expect(p.updates[0].key).toEqual([gridValue({ value: "1" }), gridValue({ value: "one" })]);
  });
});
