export interface BatchColumn {
  name: string;
  type: DataType;
  values: unknown[];
  meta?: Record<string, string>;
  /** Prebuilt Arrow data (decimals, timestamps) used instead of `values`. */
  data?: Data;
}

export function makeBatch(cols: BatchColumn[]): RecordBatch {
  const fields = cols.map((c) => new Field(c.name, c.type, true, new Map(Object.entries(c.meta ?? {}))));
  const children = cols.map((c) => c.data ?? vectorFromArray(c.values, c.type).data[0]);
  return new RecordBatch(new Schema(fields), makeData({ type: new Struct(fields), length: children[0].length, nullCount: 0, children }));
}

/** One cell of a dynamically typed column: its storage class (0 null, 1 integer, 2 real, 3 text, 4 blob) and its text. */
export type DynamicCell = [cls: number, text: string | null];

/**
 * A dynamically typed (SQLite) column as the sidecar sends it (Phase D0f): Utf8 text marked "q:dynamic", then its hidden
 * __truncated flag and its hidden UInt8 __class sibling, which name their column through "q:of".
 */
export function dynamicColumn(name: string, cells: DynamicCell[], ordinal = 0, typeName = ""): BatchColumn[] {
  return [
    { name, type: new Utf8(), values: cells.map((c) => c[1]), meta: { "q:typeName": typeName, "q:ordinal": String(ordinal), "q:dynamic": "1" } },
    { name: `${name}__truncated`, type: new Bool(), values: cells.map(() => false), meta: { "q:hidden": "flag", "q:of": name } },
    { name: `${name}__class`, type: new Uint8(), values: cells.map((c) => c[0]), meta: { "q:hidden": "class", "q:of": name } },
  ];
}

/** orders(id int, name nvarchar, qty int): three rows, one NULL qty. */
export function ordersBatch(meta: Record<string, Record<string, string>> = {}) {
  return makeBatch([
    { name: "id", type: new Int32(), values: [1, 2, 3], meta: { "q:pk": "1", "q:typeName": "int", ...meta.id } },
    { name: "name", type: new Utf8(), values: ["one", "two", "three"], meta: { "q:typeName": "nvarchar", "q:nullable": "0", ...meta.name } },
    { name: "qty", type: new Int32(), values: [10, null, 30], meta: { "q:typeName": "int", "q:nullable": "1", ...meta.qty } },
  ]);
}

export function ordersSet(index = 0, complete = true, meta: Record<string, Record<string, string>> = {}): ArrowResultSet {
  const rs = new ArrowResultSet(index);
  rs.append(ordersBatch(meta));
  if (complete) rs.finish(false);
  return rs;
}

export function registerExecution(executionId: string, ...sets: ArrowResultSet[]): ExecutionData {
  const d = new ExecutionData(executionId);
  for (const s of sets) {
    d.resultSets.push(s);
  }
  executionData.set(executionId, d);
  return d;
}

