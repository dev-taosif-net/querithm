namespace Querithm.Tests;

/// <summary>
/// D4 S11 <see cref="OracleSchemaCompare"/> without a server: catalog types to exact type text (BYTE / CHAR always said),
/// defaults (DEFAULT NULL is none, ON NULL kept), NOT NULL checks left to the column, DESC columns of function-based
/// indexes, the DDL of every step (quoted names, Oracle's own ON DELETE / identity / virtual syntax, MODIFY only for
/// what changes), refusals with the reason, normalisation and renames on tokens, the non-transactional script, and a
/// migration built from two models that adds, drops and alters in FK order.
/// </summary>
public sealed class OracleSchemaCompareRulesTests
{
    static readonly OracleSchemaCompare D = new();

    [Theory]
    [InlineData("NUMBER", null, 22, null, null, null, null, "NUMBER")]
    [InlineData("NUMBER", null, 22, null, null, null, 0, "NUMBER(*,0)")]
    [InlineData("NUMBER", null, 22, null, null, 10, 0, "NUMBER(10)")]
    [InlineData("NUMBER", null, 22, null, null, 12, 2, "NUMBER(12,2)")]
    [InlineData("FLOAT", null, 22, null, null, 126, null, "FLOAT(126)")]
    [InlineData("VARCHAR2", null, 80, 20, "C", null, null, "VARCHAR2(20 CHAR)")]
    [InlineData("VARCHAR2", null, 80, 80, "B", null, null, "VARCHAR2(80 BYTE)")]
    [InlineData("CHAR", null, 1, 1, "B", null, null, "CHAR(1 BYTE)")]
    [InlineData("NVARCHAR2", null, 80, 40, "C", null, null, "NVARCHAR2(40)")]
    [InlineData("RAW", null, 16, null, null, null, null, "RAW(16)")]
    [InlineData("TIMESTAMP(3) WITH TIME ZONE", null, 13, null, null, null, 3, "TIMESTAMP(3) WITH TIME ZONE")]
    [InlineData("DATE", null, 7, null, null, null, null, "DATE")]
    [InlineData("ADDRESS_T", "APP", 1, null, null, null, null, "\"APP\".\"ADDRESS_T\"")]
    [InlineData("XMLTYPE", "SYS", 2000, null, null, null, null, "XMLTYPE")]
    public void Catalog_types_read_back_the_same_on_any_database(string dataType, string? owner, int? len, int? charLen, string? charUsed, int? p, int? s, string expected) =>
        Assert.Equal(expected, OracleSchemaCompare.TypeText(dataType, owner, len, charLen, charUsed, p, s));

    [Theory]
    [InlineData(null, false, null)]
    [InlineData("NULL", false, null)]
    [InlineData(" null\n", false, null)]
    [InlineData("'none' ", false, "'none'")]
    [InlineData("SYSDATE", false, "SYSDATE")]
    [InlineData("1", true, "ON NULL 1")]
    public void Defaults(string? text, bool onNull, string? expected) => Assert.Equal(expected, OracleSchemaCompare.DefaultSql(text, onNull));

    [Fact]
    public void A_NOT_NULL_check_is_the_columns_own_and_a_DESC_part_is_its_column()
    {
        Assert.True(OracleSchemaCompare.IsNotNullCheck("\"CODE\" IS NOT NULL", ["CODE"]));
        Assert.False(OracleSchemaCompare.IsNotNullCheck("\"CODE\" IS NOT NULL", ["OTHER"]));
        Assert.False(OracleSchemaCompare.IsNotNullCheck("code IS NOT NULL AND x > 0", ["CODE"]));
        Assert.Equal("PLACED", OracleSchemaCompare.PlainColumn("\"PLACED\""));
        Assert.Null(OracleSchemaCompare.PlainColumn("LOWER(\"NOTE\")"));
    }

    static ModelTable T(params ModelColumn[] cols) => new() { Schema = "APP", Name = "T", Columns = cols };
    static ModelColumn C(string name, string type = "NUMBER", bool nullable = true) => new() { Name = name, Type = type, Nullable = nullable };

    [Fact]
    public void Column_definitions_use_Oracles_order_and_never_say_NOT_NULL_twice()
    {
        Assert.Equal("\"A\" NUMBER(10) GENERATED BY DEFAULT AS IDENTITY", OracleSchemaCompare.ColumnDef(C("A", "NUMBER(10)", false) with { Identity = "BY DEFAULT" }));
        Assert.Equal("\"B\" VARCHAR2(20 CHAR) DEFAULT 'x' NOT NULL", OracleSchemaCompare.ColumnDef(C("B", "VARCHAR2(20 CHAR)", false) with { Default = "'x'" }));
        Assert.Equal("\"Q\" NUMBER DEFAULT ON NULL 1", OracleSchemaCompare.ColumnDef(C("Q", nullable: false) with { Default = "ON NULL 1" }));
        Assert.Equal("\"U\" VARCHAR2(20 CHAR) GENERATED ALWAYS AS (UPPER(\"B\")) VIRTUAL", OracleSchemaCompare.ColumnDef(C("U", "VARCHAR2(20 CHAR)") with { Computed = "UPPER(\"B\")" }));
    }

    [Fact]
    public void Table_key_and_index_DDL()
    {
        var t = T(C("ID", "NUMBER(10)", false), C("CODE", "VARCHAR2(20 CHAR)", false), C("NOTE")) with
        {
            PrimaryKey = new ModelKey { Name = "T_PK", Columns = ["ID"] },
            Uniques = [new ModelKey { Name = "SYS_C001", SystemNamed = true, Columns = ["CODE"] }],
            Checks = [new ModelCheck { Name = "T_CK", Expression = "id > 0" }],
        };
        Assert.Equal("""
            CREATE TABLE "APP"."T" (
                "ID" NUMBER(10) NOT NULL,
                "CODE" VARCHAR2(20 CHAR) NOT NULL,
                "NOTE" NUMBER,
                CONSTRAINT "T_PK" PRIMARY KEY ("ID"),
                UNIQUE ("CODE"),
                CONSTRAINT "T_CK" CHECK (id > 0)
            );
            """.ReplaceLineEndings("\n"), D.CreateTable(t));
        Assert.Equal("ALTER TABLE \"APP\".\"T\" ADD CONSTRAINT \"T_PK\" PRIMARY KEY (\"ID\");", D.AddKey(t, t.PrimaryKey!, true));
        Assert.Equal("ALTER TABLE \"APP\".\"T\" ADD UNIQUE (\"CODE\");", D.AddKey(t, t.Uniques[0], false));
        Assert.Equal("ALTER TABLE \"APP\".\"T\" ADD CHECK (x > 1);", D.AddCheck(t, new ModelCheck { Name = "SYS_C9", SystemNamed = true, Expression = "x > 1" }));
        Assert.Equal("ALTER TABLE \"APP\".\"T\" DROP CONSTRAINT \"T_CK\";", D.DropConstraint(t, "T_CK"));
        Assert.Equal("CREATE INDEX \"APP\".\"T_IX\" ON \"APP\".\"T\" (\"NOTE\" DESC, LOWER(\"CODE\"));",
            D.CreateIndex(t, new ModelIndex { Name = "T_IX", Columns = ["NOTE", "LOWER(\"CODE\")"], Descending = [true, false], Kind = "NORMAL" }));
        Assert.Equal("CREATE UNIQUE INDEX \"APP\".\"T_UX\" ON \"APP\".\"T\" (\"CODE\") REVERSE;",
            D.CreateIndex(t, new ModelIndex { Name = "T_UX", Unique = true, Columns = ["CODE"], Kind = "NORMAL REVERSE" }));
        Assert.Equal("CREATE BITMAP INDEX \"APP\".\"T_BX\" ON \"APP\".\"T\" (\"NOTE\");", D.CreateIndex(t, new ModelIndex { Name = "T_BX", Columns = ["NOTE"], Kind = "BITMAP" }));
        Assert.Equal("DROP INDEX \"APP\".\"T_IX\";", D.DropIndex(t, new ModelIndex { Name = "T_IX", Columns = [] }));
        Assert.Equal("DROP TABLE \"APP\".\"T\";", D.DropTable(t));
    }

    [Fact]
    public void Foreign_keys_have_Oracles_delete_rules_and_no_ON_UPDATE()
    {
        var t = T(C("P"));
        ModelFk Fk(string onDelete, bool deferrable = false) => new() { Name = "FK", Columns = ["P"], RefSchema = "APP", RefTable = "PARENT", RefColumns = ["ID"], OnDelete = onDelete, Deferrable = deferrable };
        Assert.Equal("ALTER TABLE \"APP\".\"T\" ADD CONSTRAINT \"FK\" FOREIGN KEY (\"P\") REFERENCES \"APP\".\"PARENT\" (\"ID\");", D.AddFk(t, Fk("NO ACTION")));
        Assert.EndsWith(" ON DELETE CASCADE;", D.AddFk(t, Fk("CASCADE")));
        Assert.EndsWith(" ON DELETE SET NULL DEFERRABLE;", D.AddFk(t, Fk("SET NULL", deferrable: true)));
    }

    [Fact]
    public void A_column_change_is_one_MODIFY_per_thing_Oracle_changes_there()
    {
        var t = T();
        Assert.Equal(["ALTER TABLE \"APP\".\"T\" MODIFY (\"A\" NUMBER(12));"], D.AlterColumn(t, C("A", "NUMBER(10)"), C("A", "NUMBER(12)")));
        Assert.Equal(["ALTER TABLE \"APP\".\"T\" MODIFY (\"A\" NOT NULL);"], D.AlterColumn(t, C("A"), C("A", nullable: false)));
        Assert.Equal(["ALTER TABLE \"APP\".\"T\" MODIFY (\"A\" NULL);"], D.AlterColumn(t, C("A", nullable: false), C("A")));
        Assert.Empty(D.AlterColumn(t, C("A"), C("A") with { Default = "1" })); // defaults go through DropDefault / AddDefault
        // An ON NULL default makes the column NOT NULL by itself: no MODIFY NOT NULL as well.
        Assert.Empty(D.AlterColumn(t, C("A"), C("A", nullable: false) with { Default = "ON NULL 1" }));
        Assert.Equal(["ALTER TABLE \"APP\".\"T\" MODIFY (\"A\" GENERATED ALWAYS AS IDENTITY);"],
            D.AlterColumn(t, C("A", nullable: false) with { Identity = "BY DEFAULT" }, C("A", nullable: false) with { Identity = "ALWAYS" }));
        Assert.Equal(["ALTER TABLE \"APP\".\"T\" MODIFY (\"A\" DROP IDENTITY);", "ALTER TABLE \"APP\".\"T\" MODIFY (\"A\" NULL);"],
            D.AlterColumn(t, C("A", nullable: false) with { Identity = "BY DEFAULT" }, C("A")));
        Assert.Contains("cannot make of an existing column", D.AlterColumnRefusal(C("A"), C("A") with { Identity = "ALWAYS" }));
        Assert.Null(D.AlterColumnRefusal(C("A", "NUMBER(10)"), C("A", "NUMBER(12)")));
        Assert.Equal("ALTER TABLE \"APP\".\"T\" MODIFY (\"A\" DEFAULT NULL);", D.DropDefault(t, C("A") with { Default = "1" }));
        Assert.Null(D.DropDefault(t, C("A")));
        Assert.Equal("ALTER TABLE \"APP\".\"T\" MODIFY (\"A\" DEFAULT ON NULL 0);", D.AddDefault(t, C("A") with { Default = "ON NULL 0" }));
        Assert.Equal("ALTER TABLE \"APP\".\"T\" ADD (\"N\" NUMBER);", D.AddColumn(t, C("N")));
        Assert.Equal("ALTER TABLE \"APP\".\"T\" DROP COLUMN \"N\";", D.DropColumn(t, C("N")));
        Assert.Equal("ALTER TABLE \"APP\".\"T\" RENAME COLUMN \"A\" TO \"b\";", D.RenameColumn(t, "A", "b"));
        Assert.True(D.AlterTypeNeedsDependentsDropped); // ORA-30556 under a function-based index
        Assert.False(D.RenameColumnNeedsDependentsDropped);
    }

    [Fact]
    public void Sequences_schemas_and_modules()
    {
        var s = new ModelSequence { Schema = "APP", Name = "S", Type = "NUMBER", Start = "1", Increment = "5", Min = "1", Max = "100000", Cycle = false };
        Assert.Equal("CREATE SEQUENCE \"APP\".\"S\" START WITH 1 INCREMENT BY 5 MINVALUE 1 MAXVALUE 100000 NOCYCLE;", D.CreateSequence(s));
        Assert.Equal("ALTER SEQUENCE \"APP\".\"S\" INCREMENT BY 2 MINVALUE 1 NOMAXVALUE CYCLE;", D.AlterSequence(s, s with { Increment = "2", Max = null, Cycle = true }));
        Assert.Equal("DROP SEQUENCE \"APP\".\"S\";", D.DropSequence(s));
        Assert.Equal("CREATE USER \"NEW\" NO AUTHENTICATION;", D.CreateSchema("NEW"));
        Assert.Equal("DROP USER \"NEW\";", D.DropSchema("NEW"));
        var proc = new ModelModule { Schema = "APP", Name = "P", Kind = ModuleKind.Procedure, Definition = "CREATE OR REPLACE PROCEDURE APP.P AS BEGIN NULL; END;" };
        Assert.EndsWith("END;\n/", D.CreateModule(proc, 23));
        Assert.EndsWith("FROM dual;", D.CreateModule(new ModelModule { Schema = "APP", Name = "V", Kind = ModuleKind.View, Definition = "CREATE OR REPLACE VIEW APP.V AS SELECT 1 FROM dual" }, 23));
        Assert.False(D.NeedsDropBeforeCreate(proc, proc, 23));
        Assert.True(D.NeedsDropBeforeCreate(proc with { Kind = ModuleKind.Function }, proc, 23));
        Assert.Equal("DROP PACKAGE BODY \"APP\".\"PKG\";", D.DropModule(new ModelModule { Schema = "APP", Name = "PKG", Kind = ModuleKind.PackageBody }));
        Assert.False(D.DependencyBlocks(proc));
        Assert.Null(D.RefreshModule(proc));
        Assert.Throws<NotSupportedException>(() => D.CreateType(new ModelType { Schema = "APP", Name = "T", Kind = "object" }));
    }

    [Fact]
    public void Renames_tables_by_ALTER_and_refuse_what_Oracle_cannot_rename_in_place()
    {
        Assert.Equal("ALTER TABLE \"APP\".\"T\" RENAME TO \"T2\";", D.RenameObject(RefKind.Table, "APP", "T", "T2"));
        Assert.Throws<NotSupportedException>(() => D.RenameObject(RefKind.View, "APP", "V", "V2"));
        Assert.Contains("own schema", Assert.Throws<NotSupportedException>(() => D.RenameObject(RefKind.Sequence, "APP", "S", "S2")).Message);
    }

    [Fact]
    public void Normalisation_is_on_tokens()
    {
        Assert.Equal(D.NormalizeExpression("((status IN ('N', 'P')))"), D.NormalizeExpression("\"STATUS\"   in ('N','P')"));
        Assert.NotEqual(D.NormalizeExpression("status IN ('n')"), D.NormalizeExpression("status IN ('N')")); // literals keep their case
        Assert.NotEqual(D.NormalizeExpression("\"Status\" > 0"), D.NormalizeExpression("status > 0")); // a quoted mixed-case name is another column
        Assert.Equal(D.NormalizeBody("CREATE OR REPLACE EDITIONABLE PROCEDURE app.p AS\nBEGIN NULL; END;\n/"), D.NormalizeBody("create procedure APP.P as begin null; end;"));
        Assert.Equal("PROCEDURE APP.P AS BEGIN NULL; END;", D.WithoutHeader("CREATE OR REPLACE PROCEDURE APP.P AS BEGIN NULL; END;\n/"));
        Assert.Equal("VIEW APP.V AS SELECT 1 FROM dual;", D.WithoutHeader("CREATE OR REPLACE VIEW APP.V AS SELECT 1 FROM dual;"));
    }

    [Fact]
    public void Schema_and_identifier_renames_are_on_tokens()
    {
        Assert.Equal("SELECT * FROM PROD.t JOIN \"PROD\".u ON 1 = 1 WHERE x = 'dev.t' AND t.dev = 1",
            D.RenameSchema("SELECT * FROM dev.t JOIN \"DEV\".u ON 1 = 1 WHERE x = 'dev.t' AND t.dev = 1", "DEV", "PROD"));
        Assert.Equal("UPPER(NEW_CODE) || \"code\"", D.RenameIdentifier("UPPER(code) || \"code\"", "CODE", "NEW_CODE"));
        Assert.Equal("UPPER(\"New\")", D.RenameIdentifier("UPPER(code)", "CODE", "New"));
    }

    [Fact]
    public void The_script_is_not_one_transaction_and_says_so()
    {
        Assert.False(D.TransactionalDdl);
        Assert.False(((ISchemaCompareDialect)D).DatabaseIsSchema);
        var sql = D.Wrap([new MigrationStep(MigrationPhase.Tables, "DROP TABLE \"APP\".\"T\";", "drop table APP.T")], "-- header");
        Assert.StartsWith("-- header\n\n-- Oracle commits every DDL statement on its own", sql);
        Assert.Contains("-- drop table APP.T\nDROP TABLE \"APP\".\"T\";", sql);
    }

    [Fact]
    public void A_migration_from_two_models_adds_drops_and_alters_in_foreign_key_order()
    {
        ModelTable Parent(params ModelColumn[] extra) => new()
        {
            Schema = "APP", Name = "PARENT", Columns = [C("ID", "NUMBER(10)", false), .. extra], PrimaryKey = new ModelKey { Name = "PARENT_PK", Columns = ["ID"] },
        };
        var child = new ModelTable
        {
            Schema = "APP", Name = "CHILD", Columns = [C("ID", "NUMBER(10)", false), C("PARENT_ID", "NUMBER(10)")], PrimaryKey = new ModelKey { Name = "CHILD_PK", Columns = ["ID"] },
            Fks = [new ModelFk { Name = "CHILD_FK", Columns = ["PARENT_ID"], RefSchema = "APP", RefTable = "PARENT", RefColumns = ["ID"], OnDelete = "CASCADE" }],
        };
        SchemaModel M(params ModelTable[] tables) => new() { Engine = Engine.Oracle, Database = "FREEPDB1", Schemas = ["APP"], Tables = tables, Modules = [] };
        var source = M(Parent(C("NAME", "VARCHAR2(40 CHAR)")), child);
        var target = M(Parent(C("NAME", "VARCHAR2(20 CHAR)")));
        var cmp = SchemaComparer.Compare(source, target, D);
        var keys = cmp.Items.Where(i => i.Class != CompareClass.Identical).Select(i => i.Key).ToList();
        var r = new MigrationScriptBuilder(cmp).Build(keys, [], includeDataLoss: true, "-- h");
        var create = r.Sql.IndexOf("CREATE TABLE \"APP\".\"CHILD\"", StringComparison.Ordinal);
        var modify = r.Sql.IndexOf("MODIFY (\"NAME\" VARCHAR2(40 CHAR))", StringComparison.Ordinal);
        var fk = r.Sql.IndexOf("ADD CONSTRAINT \"CHILD_FK\" FOREIGN KEY", StringComparison.Ordinal);
        Assert.True(modify > 0 && create > 0 && fk > create, r.Sql);
        Assert.False(r.Transactional);
        Assert.EndsWith(" ON DELETE CASCADE;", r.Sql[fk..].Split('\n')[0]);
    }
