            var (p, sid) = await h.OpenMssqlAsync(Db);
            await Ok(h, sid, """
                DROP TABLE IF EXISTS dbo.q_edit; DROP TABLE IF EXISTS dbo.q_plain; DROP TABLE IF EXISTS dbo.q_trig; DROP TABLE IF EXISTS dbo.q_audit;
                CREATE TABLE dbo.q_edit (id int IDENTITY PRIMARY KEY, name nvarchar(50) NOT NULL, qty int NULL, price decimal(10,2) NULL, rv rowversion);
                INSERT dbo.q_edit (name, qty, price) VALUES (N'one', 1, 1.50), (N'two', 2, 2.50), (N'three', 3, NULL);
                CREATE TABLE dbo.q_plain (id int PRIMARY KEY, name nvarchar(50) NULL, ratio float NULL);
                INSERT dbo.q_plain VALUES (1, N'a', 0.1), (2, N'b', 0.2);
                CREATE TABLE dbo.q_audit (n int);
                CREATE TABLE dbo.q_trig (id int PRIMARY KEY, v int NULL);
                INSERT dbo.q_trig VALUES (1, 10);
                """);
            await Ok(h, sid, "CREATE TRIGGER dbo.q_trig_upd ON dbo.q_trig AFTER UPDATE AS BEGIN INSERT dbo.q_audit VALUES (1), (2), (3); END");
            await RefreshAsync(h, p);
            return (h, p, sid);
        }
        else
        {
            await h.EnsureDatabaseAsync(Engine.Pg, Db);
            var p = await h.Rpc.ProfileSave(new Profile
            {
                Id = "", Name = "Fixture PG edit", Engine = Engine.Pg, Host = "localhost", Port = 54329, Auth = AuthKind.Password, Username = "postgres",
                Environment = EnvironmentKind.Dev, TlsMode = TlsMode.Prefer, DatabaseDefault = Db,
            });
            var sid = (await h.Rpc.SessionOpen(new SessionOpenParams { ProfileId = p.Id, Secret = TestHost.PgPassword, Database = Db })).SessionId;
            await Ok(h, sid, """
                DROP TABLE IF EXISTS q_edit; DROP TABLE IF EXISTS q_plain;
                CREATE TABLE q_edit (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL, qty int, price numeric(10,2));
                INSERT INTO q_edit (name, qty, price) VALUES ('one', 1, 1.50), ('two', 2, 2.50), ('three', 3, NULL);
                CREATE TABLE q_plain (id int PRIMARY KEY, name text, ratio float8);
                INSERT INTO q_plain VALUES (1, 'a', 0.1), (2, 'b', 0.2);
