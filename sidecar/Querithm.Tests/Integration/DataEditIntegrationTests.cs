    [IntegrationTheory, MemberData(nameof(Engines))]
    public async Task An_insert_trigger_does_not_replace_the_new_key(string engine)
    {
        var (h, p, sid) = await SetupAsync(engine);
        await using var _h = h;
        if (engine == "mssql")
        {
            // The trigger's result set comes before the key SELECT of the insert batch.
            await Ok(h, sid, "DROP TABLE IF EXISTS dbo.q_trig_ins; CREATE TABLE dbo.q_trig_ins (id int IDENTITY(100,1) PRIMARY KEY, v int NULL);");
            await Ok(h, sid, "CREATE TRIGGER dbo.q_trig_ins_t ON dbo.q_trig_ins AFTER INSERT AS BEGIN SELECT 999 AS noise; END");
        }
        else
        {
            // PostgreSQL triggers cannot send rows to the client: RETURNING stays the only result, trigger or not.
            await Ok(h, sid, """
                DROP TABLE IF EXISTS q_trig_ins;
                CREATE TABLE q_trig_ins (id int GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY, v int);
                CREATE OR REPLACE FUNCTION q_trig_ins_f() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN NEW.v := coalesce(NEW.v, 0) + 1; RETURN NEW; END $$;
                CREATE TRIGGER q_trig_ins_t BEFORE INSERT ON q_trig_ins FOR EACH ROW EXECUTE FUNCTION q_trig_ins_f();
                """);
        }
        await RefreshAsync(h, p);
        var (exec, edit) = await SelectAsync(h, sid, $"SELECT id, v FROM {T(engine, "q_trig_ins")}");
        Assert.True(edit.Editable, edit.Reason);
        var r = await h.Rpc.DataApplyPatch(new GridPatchParams
        {
            SessionId = sid, ExecutionId = exec, Inserts = [new GridRowInsert { TempIndex = 0, Values = new() { ["v"] = V("7") } }],
        });
        Assert.True(r.Ok, r.Error);
        Assert.Equal("100", Assert.Single(r.InsertedKeys!["0"]).Text);
    }
