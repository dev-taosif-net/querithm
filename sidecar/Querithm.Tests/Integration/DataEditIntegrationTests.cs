    [IntegrationTheory, MemberData(nameof(Engines))]
    public async Task Prod_writes_need_confirmation_every_time(string engine)
    {
        var (h, dev, _) = await SetupAsync(engine);
        await using var _h = h;
        var prod = await h.Rpc.ProfileSave(dev with { Id = "", Name = "Fixture prod", Environment = EnvironmentKind.Prod });
        var sid = (await h.Rpc.SessionOpen(new SessionOpenParams { ProfileId = prod.Id, Database = Db, Secret = engine == "pg" ? TestHost.PgPassword : TestHost.MssqlPassword })).SessionId;
        await RefreshAsync(h, prod);
        var (done, _, _) = await h.RunAsync(sid, "SELECT 1", new ExecuteOptions { ConfirmedProd = true });
        Assert.Equal(ExecState.Done, done.State);
        var (exec, edit) = await SelectAsync(h, sid, $"SELECT id, name FROM {T(engine, "q_edit")} ORDER BY id");
        Assert.True(edit.Editable, edit.Reason);
        var token = await TokenAsync(h, sid, exec, "3");
        GridPatchParams Patch(bool confirmedProd, bool destructive) => new()
        {
            SessionId = sid, ExecutionId = exec, ConfirmedProd = confirmedProd, ConfirmedDestructive = destructive,
            Deletes = [new GridRowDelete { RowIndex = 2, Key = [V("3")], Token = token }],
        };
        // Already past the first-run confirm, yet every Querithm-generated write on Prod is confirmed again.
        Assert.Equal(GuardReason.ProdWrite, (await h.Rpc.DataApplyPatch(Patch(false, false))).Blocked?.Reason);
        Assert.Equal(GuardReason.Destructive, (await h.Rpc.DataApplyPatch(Patch(true, false))).Blocked?.Reason);
        var r = await h.Rpc.DataApplyPatch(Patch(true, true));
        Assert.True(r.Ok, r.Error);
    }

    [IntegrationTheory, MemberData(nameof(Engines))]
    public async Task Joins_views_and_switched_databases_are_refused(string engine)
    {
        var (h, _, sid) = await SetupAsync(engine);
        await using var _h = h;
        var (_, join) = await SelectAsync(h, sid, $"SELECT a.id, b.name FROM {T(engine, "q_edit")} a JOIN {T(engine, "q_plain")} b ON b.id = a.id");
