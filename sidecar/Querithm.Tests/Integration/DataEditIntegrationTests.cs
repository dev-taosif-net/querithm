            await RefreshAsync(h, p);
            return (h, p, sid);
        }
    }

    static async Task RefreshAsync(TestHost h, Profile p)
    {
        h.Services.Metadata.Refresh(new RefreshParams { ProfileId = p.Id, Database = Db, Full = true });
        await Task.Delay(100);
        await h.Services.Metadata.WaitAsync(p.Id, Db);
    }

    static async Task Ok(TestHost h, string sid, string sql)
    {
        var (done, _, id) = await h.RunAsync(sid, sql);
        Assert.True(done.State == ExecState.Done, string.Join("\n", h.Messages(id)));
    }

    static string T(string engine, string table) => engine == "mssql" ? "dbo." + table : table;

    static async Task<(string ExecutionId, ResultEditInfo Edit)> SelectAsync(TestHost h, string sid, string sql)
    {
        var (done, _, id) = await h.RunAsync(sid, sql);
        Assert.True(done.State == ExecState.Done, string.Join("\n", h.Messages(id)));
        var edit = h.Notifier.Of<QueryResultSetEvent>().Single(e => e.ExecutionId == id).Edit;
        Assert.NotNull(edit);
        return (id, edit);
    }

    static GridValue V(string? s) => s == null ? new GridValue { IsNull = true } : new GridValue { Text = s };

    static async Task<string?> TokenAsync(TestHost h, string sid, string exec, string key, Dictionary<string, GridValue>? expect = null) =>
        (await h.Rpc.DataRowTokens(new RowTokensParams { SessionId = sid, ExecutionId = exec, Keys = [[V(key)]], Expect = expect == null ? null : [expect] })).Tokens[0];

    static async Task<string?> ScalarAsync(TestHost h, string sid, string sql)
    {
        var (done, b, id) = await h.RunAsync(sid, sql);
        Assert.True(done.State == ExecState.Done, string.Join("\n", h.Messages(id)));
        var col = b[0].Column(0);
        return col switch
        {
            StringArray s => s.GetString(0),
            Int32Array i => i.GetValue(0)?.ToString(),
            Int64Array l => l.GetValue(0)?.ToString(),
            _ => col.IsNull(0) ? null : col.ToString(),
        };
    }

    [IntegrationTheory, MemberData(nameof(Engines))]
    public async Task Update_insert_and_delete_round_trip(string engine)
    {
        var (h, _, sid) = await SetupAsync(engine);
        await using var _h = h;
        var (exec, edit) = await SelectAsync(h, sid, $"SELECT id, name, qty FROM {T(engine, "q_edit")} ORDER BY id");
        Assert.True(edit.Editable, edit.Reason);
        Assert.Equal(["id"], edit.KeyColumns);
        Assert.Equal(engine == "pg" ? "xmin" : "rowversion", edit.TokenKind);

        var token = await TokenAsync(h, sid, exec, "1", new() { ["name"] = V("one") });
        Assert.False(string.IsNullOrEmpty(token));
        // A displayed value that no longer matches the server means the row changed since the query: no token.
        Assert.Null(await TokenAsync(h, sid, exec, "1", new() { ["name"] = V("not one") }));
        Assert.Null(await TokenAsync(h, sid, exec, "999"));

        var patch = new GridPatchParams
        {
            SessionId = sid, ExecutionId = exec,
            Updates = [new GridRowUpdate { RowIndex = 0, Key = [V("1")], Token = token, Changes = new() { ["name"] = V("uno"), ["qty"] = V(null) }, Original = new() { ["name"] = V("one"), ["qty"] = V("1") } }],
            Inserts = [new GridRowInsert { TempIndex = 0, Values = new() { ["name"] = V("four"), ["qty"] = V("4") } }],
        };
        var preview = await h.Rpc.DataPreviewPatch(patch);
        Assert.Equal(2, preview.StatementCount);
        Assert.Contains("uno", preview.Sql);
        var r = await h.Rpc.DataApplyPatch(patch);
        Assert.True(r.Ok, r.Error);
        Assert.Equal((1, 1), (r.AppliedUpdates, r.AppliedInserts));
        var newId = Assert.Single(r.InsertedKeys!["0"]).Text;
        Assert.Equal("4", newId);
        Assert.Equal("uno", await ScalarAsync(h, sid, $"SELECT name FROM {T(engine, "q_edit")} WHERE id = 1"));
        Assert.Null(await ScalarAsync(h, sid, $"SELECT {(engine == "pg" ? "qty::text" : "CAST(qty AS nvarchar(10))")} FROM {T(engine, "q_edit")} WHERE id = 1"));

        var delToken = await TokenAsync(h, sid, exec, "3");
        var del = await h.Rpc.DataApplyPatch(new GridPatchParams { SessionId = sid, ExecutionId = exec, Deletes = [new GridRowDelete { RowIndex = 2, Key = [V("3")], Token = delToken }] });
        Assert.True(del.Ok, del.Error);
        Assert.Equal(1, del.AppliedDeletes);
        Assert.Equal("0", await ScalarAsync(h, sid, $"SELECT {(engine == "pg" ? "count(*)::int" : "count(*)")} FROM {T(engine, "q_edit")} WHERE id = 3"));
        // The write is one execution in history, like any query.
        Assert.Contains(h.Services.History.List(new HistoryListParams { Limit = 50 }), e => e.Sql.Contains("Grid changes to"));
    }

    [IntegrationTheory, MemberData(nameof(Engines))]
    public async Task A_row_changed_by_another_session_is_a_conflict_not_a_lost_update(string engine)
    {
        var (h, p, sid) = await SetupAsync(engine);
        await using var _h = h;
        var (exec, _) = await SelectAsync(h, sid, $"SELECT id, name FROM {T(engine, "q_edit")} ORDER BY id");
        var token = await TokenAsync(h, sid, exec, "2");
        var other = (await h.Rpc.SessionOpen(new SessionOpenParams { ProfileId = p.Id, Database = Db, Secret = engine == "pg" ? TestHost.PgPassword : TestHost.MssqlPassword })).SessionId;
        await Ok(h, other, $"UPDATE {T(engine, "q_edit")} SET name = 'theirs' WHERE id = 2");

        var r = await h.Rpc.DataApplyPatch(new GridPatchParams
        {
            SessionId = sid, ExecutionId = exec,
            Updates = [new GridRowUpdate { RowIndex = 1, Key = [V("2")], Token = token, Changes = new() { ["name"] = V("mine") }, Original = new() { ["name"] = V("two") } }],
        });
        Assert.False(r.Ok);
        var c = Assert.Single(r.Conflicts!);
        Assert.Equal(("changedOnServer", 1), (c.Reason, c.RowIndex));
        Assert.Equal("theirs", c.Current!["name"].Text);
        Assert.Equal("theirs", await ScalarAsync(h, sid, $"SELECT name FROM {T(engine, "q_edit")} WHERE id = 2"));

        // Overwrite after review matches on the key only.
        var forced = await h.Rpc.DataApplyPatch(new GridPatchParams
        {
            SessionId = sid, ExecutionId = exec, ForceOverwriteConflicts = true,
            Updates = [new GridRowUpdate { RowIndex = 1, Key = [V("2")], Changes = new() { ["name"] = V("mine") }, Original = [] }],
        });
        Assert.True(forced.Ok, forced.Error);
        Assert.Equal("mine", await ScalarAsync(h, sid, $"SELECT name FROM {T(engine, "q_edit")} WHERE id = 2"));
    }

    [IntegrationTheory, MemberData(nameof(Engines))]
    public async Task Original_values_detect_conflicts_without_a_token(string engine)
    {
        var (h, p, sid) = await SetupAsync(engine);
        await using var _h = h;
        var (exec, edit) = await SelectAsync(h, sid, $"SELECT id, name, ratio FROM {T(engine, "q_plain")} ORDER BY id");
        Assert.True(edit.Editable, edit.Reason);
        var other = (await h.Rpc.SessionOpen(new SessionOpenParams { ProfileId = p.Id, Database = Db, Secret = engine == "pg" ? TestHost.PgPassword : TestHost.MssqlPassword })).SessionId;
        var token = engine == "pg" ? await TokenAsync(h, sid, exec, "1") : null;
        await Ok(h, other, $"UPDATE {T(engine, "q_plain")} SET name = 'changed' WHERE id = 1");
        var r = await h.Rpc.DataApplyPatch(new GridPatchParams
        {
            SessionId = sid, ExecutionId = exec,
            Updates = [new GridRowUpdate { RowIndex = 0, Key = [V("1")], Token = token, Changes = new() { ["name"] = V("mine") }, Original = new() { ["name"] = V("a") } }],
        });
        Assert.False(r.Ok);
        Assert.Equal("changedOnServer", Assert.Single(r.Conflicts!).Reason);

        // A float column is written but not compared (its text form is not exact).
        var r2 = await h.Rpc.DataApplyPatch(new GridPatchParams
        {
            SessionId = sid, ExecutionId = exec,
            Updates = [new GridRowUpdate { RowIndex = 1, Key = [V("2")], Token = engine == "pg" ? await TokenAsync(h, sid, exec, "2") : null, Changes = new() { ["ratio"] = V("0.75") }, Original = new() { ["ratio"] = V("0.2000001") } }],
        });
        Assert.True(r2.Ok, r2.Error);
    }

    [IntegrationTheory, MemberData(nameof(Engines))]
    public async Task Changes_inside_an_open_transaction_use_a_savepoint(string engine)
    {
        var (h, _, sid) = await SetupAsync(engine);
        await using var _h = h;
        var (exec, _) = await SelectAsync(h, sid, $"SELECT id, name FROM {T(engine, "q_edit")} ORDER BY id");
        await h.Rpc.TxBegin(new SessionRef { SessionId = sid });
        var token = await TokenAsync(h, sid, exec, "1");
        var bad = await h.Rpc.DataApplyPatch(new GridPatchParams
        {
            SessionId = sid, ExecutionId = exec,
            Updates =
            [
                new GridRowUpdate { RowIndex = 0, Key = [V("1")], Token = token, Changes = new() { ["name"] = V("in tx") }, Original = new() { ["name"] = V("one") } },
                new GridRowUpdate { RowIndex = 1, Key = [V("2")], Token = engine == "pg" ? "1" : "0x0000000000000001", Changes = new() { ["name"] = V("stale") }, Original = new() { ["name"] = V("two") } },
            ],
        });
        Assert.False(bad.Ok);
        // Rolled back to the savepoint: the transaction is still open and row 1 is untouched.
        Assert.Equal(TxState.Open, (await h.Rpc.SessionStateGet(new SessionRef { SessionId = sid })).TxState);
        Assert.Equal("one", await ScalarAsync(h, sid, $"SELECT name FROM {T(engine, "q_edit")} WHERE id = 1"));
        var good = await h.Rpc.DataApplyPatch(new GridPatchParams
        {
            SessionId = sid, ExecutionId = exec,
            Updates = [new GridRowUpdate { RowIndex = 0, Key = [V("1")], Token = token, Changes = new() { ["name"] = V("in tx") }, Original = new() { ["name"] = V("one") } }],
        });
        Assert.True(good.Ok, good.Error);
        Assert.Equal(TxState.Open, (await h.Rpc.SessionStateGet(new SessionRef { SessionId = sid })).TxState);
        await h.Rpc.TxRollback(new SessionRef { SessionId = sid });
        Assert.Equal("one", await ScalarAsync(h, sid, $"SELECT name FROM {T(engine, "q_edit")} WHERE id = 1"));
    }

