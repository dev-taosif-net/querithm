    sealed class Host : IAsyncDisposable
    {
        public CapturingNotifier Notifier { get; } = new();
        public CapturingFrames Frames { get; } = new();
        public Services Services { get; }
        public RpcServer Rpc { get; }
        public string Dir { get; } = Directory.CreateTempSubdirectory("qora-s11-host-").FullName;

        public Host()
        {
            Services = Services.Create(LocalStore.InMemory(), Frames, Notifier, NullLoggerFactory.Instance,
                new ProviderRegistry(EngineSetup.Providers(Dir), ProviderRegistry.HiddenEngines(EngineSetup.BehindFlag, "oracle")), Dir);
            Rpc = new RpcServer(Services, () => { });
        }

        public async ValueTask DisposeAsync()
        {
            await Services.DisposeAsync();
            try { Directory.Delete(Dir, true); } catch { /* best effort */ }
        }
    }

    static async Task<(Host H, string Sid, string ProfileId)> HostAsync()
    {
        var h = new Host();
        var p = await h.Rpc.ProfileSave(ProfileOf());
        var s = await h.Rpc.SessionOpen(new SessionOpenParams { ProfileId = p.Id, Secret = Secret });
        return (h, s.SessionId, p.Id);
    }

    static async Task<(QueryDoneEvent Done, List<(ushort Result, RecordBatch Batch)> Batches, List<ServerMessage> Messages)> RunAsync(Host h, string sid, string sql, bool serverOutput = false)
    {
        var r = await h.Rpc.QueryExecute(new QueryExecuteParams { SessionId = sid, Sql = sql, Options = new ExecuteOptions { ServerOutput = serverOutput } });
        Assert.Null(r.Blocked);
        var done = await h.Notifier.WaitDone(r.ExecutionId!, 120_000);
        var batches = h.Frames.For(r.ExecutionId!).Where(f => f.Kind == 0x02).Select(f => (f.ResultIndex, TestHost.ReadBatch(f.Payload))).ToList();
        return (done, batches, h.Notifier.Of<ServerMessage>().Where(m => m.ExecutionId == r.ExecutionId).ToList());
    }

    static string? Text(RecordBatch b, string column, int row = 0) => b.Column(b.Schema.GetFieldIndex(column)) switch
    {
        StringArray s => s.GetString(row),
        var a => a.GetType().GetMethod("GetValue")?.Invoke(a, [row])?.ToString(),
    };

    static ScriptArgument Arg(string name, string? text) => new() { Name = name, Value = text == null ? new GridValue { IsNull = true } : new GridValue { Text = text } };

    [IntegrationFact]
    public async Task Execute_calls_a_procedure_with_typed_values_and_returns_OUT_IN_OUT_and_the_ref_cursor()
    {
        await SchemaAsync();
        var (h, sid, pid) = await HostAsync();
        await using var _ = h;
        var obj = new ObjectRef { ProfileId = pid, Database = OracleIntegrationTests.Service, Schema = Schema, Name = "Q_S11_P", Kind = ObjectKind.Proc };
        var sql = (await h.Rpc.MetaScript(new ScriptParams
        {
            SessionId = sid, Object = obj, Kind = ScriptKind.Execute, Arguments = [Arg("A", "41.5"), Arg("C", "21"), Arg("E", "2026-03-04 00:00:00")],
        })).Sql;
        Assert.Contains("A => 41.5", sql);
        Assert.Contains("E => TO_DATE('2026-03-04 00:00:00', 'SYYYY-MM-DD HH24:MI:SS')", sql);
        var (done, batches, _) = await RunAsync(h, sid, sql);
        Assert.Equal(ExecState.Done, done.State);
        var outRow = batches.Single(b => b.Batch.Schema.GetFieldIndex("B") >= 0).Batch;
        Assert.Equal("got 41.5 on 2026-03-04", Text(outRow, "B"));
        Assert.Equal("42", Text(outRow, "C"));
        var cursor = batches.Single(b => b.Batch.Schema.GetFieldIndex("NAME") >= 0).Batch;
        Assert.Equal(2, cursor.Length);
        Assert.Equal("Sales", Text(cursor, "NAME"));

        // Script as ▸ EXECUTE: the template leaves the defaulted E out and passes NULL for the rest.
        var template = (await h.Rpc.MetaScript(new ScriptParams { SessionId = sid, Object = obj, Kind = ScriptKind.Execute })).Sql;
        Assert.Contains("A => NULL", template);
        Assert.Contains("-- E => …", template);
        Assert.Equal(ExecState.Done, (await RunAsync(h, sid, template)).Done.State);
    }

    [IntegrationFact]
    public async Task Execute_returns_a_function_result_and_a_boolean_as_text()
    {
        await SchemaAsync();
        var (h, sid, pid) = await HostAsync();
        await using var _ = h;
        ObjectRef F(string name) => new() { ProfileId = pid, Database = OracleIntegrationTests.Service, Schema = Schema, Name = name, Kind = ObjectKind.Func };
        var f = (await h.Rpc.MetaScript(new ScriptParams { SessionId = sid, Object = F("Q_S11_F"), Kind = ScriptKind.Execute, Arguments = [Arg("X", "1e3")] })).Sql;
        var ran = await RunAsync(h, sid, f);
        Assert.Equal("1001", Text(Assert.Single(ran.Batches).Batch, "RESULT"));
        var fb = (await h.Rpc.MetaScript(new ScriptParams { SessionId = sid, Object = F("Q_S11_FB"), Kind = ScriptKind.Execute, Arguments = [] })).Sql;
        Assert.Equal("TRUE", Text(Assert.Single((await RunAsync(h, sid, fb)).Batches).Batch, "RESULT"));
        // CHAR / NCHAR parameters have no length in ALL_ARGUMENTS: more than one character is taken (regression: CHAR(1)).
        var fc = (await h.Rpc.MetaScript(new ScriptParams { SessionId = sid, Object = F("Q_S11_FC"), Kind = ScriptKind.Execute, Arguments = [Arg("C", "AB"), Arg("N", "αβγ")] })).Sql;
        Assert.Equal("AB|αβγ", Text(Assert.Single((await RunAsync(h, sid, fc)).Batches).Batch, "RESULT"));
    }

    [IntegrationFact]
    public async Task A_value_the_parameter_cannot_take_is_refused_before_anything_runs()
    {
        await SchemaAsync();
        var (h, sid, pid) = await HostAsync();
        await using var _ = h;
        var obj = new ObjectRef { ProfileId = pid, Database = OracleIntegrationTests.Service, Schema = Schema, Name = "Q_S11_P", Kind = ObjectKind.Proc };
        var bad = await Assert.ThrowsAsync<QuerithmException>(() => h.Rpc.MetaScript(new ScriptParams { SessionId = sid, Object = obj, Kind = ScriptKind.Execute, Arguments = [Arg("A", "twelve")] }));
        Assert.Contains("A:", bad.Message);
        Assert.Contains("not a number", bad.Message);
        var date = await Assert.ThrowsAsync<QuerithmException>(() => h.Rpc.MetaScript(new ScriptParams { SessionId = sid, Object = obj, Kind = ScriptKind.Execute, Arguments = [Arg("E", "yesterday")] }));
        Assert.Contains("E:", date.Message);
        var unknown = await Assert.ThrowsAsync<QuerithmException>(() => h.Rpc.MetaScript(new ScriptParams { SessionId = sid, Object = obj, Kind = ScriptKind.Execute, Arguments = [Arg("Z", "1")] }));
        Assert.Contains("no parameter Z", unknown.Message);
    }

