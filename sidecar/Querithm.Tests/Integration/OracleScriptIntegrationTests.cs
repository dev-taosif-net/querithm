    }

    [IntegrationFact]
    public async Task SELECT_and_trigger_ENABLE_DISABLE_run()
    {
        await SchemaAsync();
        await using var c = await OpenAsync();
        var s = new OracleScripter(new OracleMetadata());
        var select = await s.ScriptAsync(c, Ref("Q_S11_DEPT", ObjectKind.Table), ScriptKind.SelectTop, Timeout());
        await using (var cmd = c.CreateCommand())
        {
            cmd.CommandText = select.TrimEnd(';');
            await using var r = await cmd.ExecuteReaderAsync(Timeout());
            Assert.True(await r.ReadAsync(Timeout()));
        }
        await RunScriptAsync(c, await s.ScriptAsync(c, Ref("Q_S11_TRG", ObjectKind.Trigger), ScriptKind.Disable, Timeout()));
        Assert.Equal("DISABLED", await ScalarAsync(c, "SELECT status FROM user_triggers WHERE trigger_name = 'Q_S11_TRG'"));
        await RunScriptAsync(c, await s.ScriptAsync(c, Ref("Q_S11_TRG", ObjectKind.Trigger), ScriptKind.Enable, Timeout()));
        Assert.Equal("ENABLED", await ScalarAsync(c, "SELECT status FROM user_triggers WHERE trigger_name = 'Q_S11_TRG'"));
    }

