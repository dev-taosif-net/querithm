/// <summary>
/// D4 S11 against the Oracle Free fixture (QUERITHM_IT=1): Script as ▸ for every kind runs unchanged (DROP and CREATE,
/// CREATE OR REPLACE, ENABLE / DISABLE, SELECT), the Execute block with IN / OUT / IN OUT / ref cursor parameters through
