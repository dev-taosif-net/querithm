    const string App = OracleIntegrationTests.AppUser, Schema = "QUERITHM_APP";

    static Profile ProfileOf() => new()
    {
        Id = "", Name = "ora-s11", Engine = Engine.Oracle, Host = "127.0.0.1", Port = OracleIntegrationTests.Port, Auth = AuthKind.Password, Username = App,
        DatabaseDefault = OracleIntegrationTests.Service, TlsMode = TlsMode.Disable, TimeoutS = 30,
    };

    static string Secret => FixtureSecrets.Password("oracle");

    internal static CancellationToken Timeout(int seconds = 120) => new CancellationTokenSource(TimeSpan.FromSeconds(seconds)).Token;

    internal static async Task<DbConnection> OpenAsync() =>
        await new OracleProvider(Directory.CreateTempSubdirectory("qora-s11-").FullName).OpenAsync(ProfileOf(), Secret, null, null, Timeout());

    internal static async Task ExecAsync(DbConnection c, string sql)
    {
        await using var cmd = c.CreateCommand();
        cmd.CommandText = sql;
        cmd.CommandTimeout = 300;
        await cmd.ExecuteNonQueryAsync(Timeout());
    }

    internal static async Task<object?> ScalarAsync(DbConnection c, string sql)
    {
        await using var cmd = c.CreateCommand();
        cmd.CommandText = sql;
        var v = await cmd.ExecuteScalarAsync(Timeout());
        return v is DBNull ? null : v;
    }

    /// <summary>Each batch of a script as the splitter cuts it, run as it is.</summary>
    internal static async Task RunScriptAsync(DbConnection c, string script)
    {
        foreach (var st in OracleSplitter.Split(script).Where(s => s.Kind != OracleStatementKind.ClientCommand))
            if (st.Code.Any()) await ExecAsync(c, script[st.Start..st.End]);
    }

    internal static Task DropAsync(DbConnection c, string kind, string name) => ExecAsync(c, $"""
        BEGIN EXECUTE IMMEDIATE 'DROP {kind} {name}{(kind == "TABLE" ? " CASCADE CONSTRAINTS PURGE" : kind == "TYPE" ? " FORCE" : "")}';
        EXCEPTION WHEN OTHERS THEN IF SQLCODE NOT IN (-942, -4043, -4080, -2289, -1434, -12003) THEN RAISE; END IF; END;
        """);

    static readonly SemaphoreSlim Once = new(1, 1);
    static bool _made;

    /// <summary>The S11 objects in the app user's schema, created once per run.</summary>
    static async Task SchemaAsync()
    {
        await Once.WaitAsync();
        try
        {
            if (_made) return;
            await using var c = await OpenAsync();
            foreach (var (k, n) in new[] { ("MATERIALIZED VIEW", "q_s11_mv"), ("TRIGGER", "q_s11_trg"), ("VIEW", "q_s11_v"), ("PROCEDURE", "q_s11_p"), ("FUNCTION", "q_s11_f"),
                         ("FUNCTION", "q_s11_fb"), ("FUNCTION", "q_s11_fc"), ("SYNONYM", "q_s11_syn"), ("SEQUENCE", "q_s11_seq"), ("TABLE", "q_s11_emp"), ("TABLE", "q_s11_dept"), ("TYPE", "q_s11_t"),
                         ("PROCEDURE", "q_s11_wrapped") })
                await DropAsync(c, k, n);
            await RunScriptAsync(c, """
                CREATE TABLE q_s11_dept (id NUMBER(6) PRIMARY KEY, name VARCHAR2(40 CHAR) NOT NULL);
                CREATE TABLE q_s11_emp (
                  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  dept_id NUMBER(6) REFERENCES q_s11_dept (id),
                  name VARCHAR2(60) DEFAULT 'none' NOT NULL,
                  salary NUMBER(10,2) CHECK (salary >= 0),
                  upper_name GENERATED ALWAYS AS (UPPER(name)) VIRTUAL,
                  CONSTRAINT q_s11_emp_name_uk UNIQUE (name));
                CREATE INDEX q_s11_emp_dept_ix ON q_s11_emp (dept_id, salary DESC);
                CREATE SEQUENCE q_s11_seq START WITH 5 INCREMENT BY 2;
                CREATE VIEW q_s11_v (dept, people) AS SELECT d.name, COUNT(e.id) FROM q_s11_dept d LEFT JOIN q_s11_emp e ON e.dept_id = d.id GROUP BY d.name;
                CREATE SYNONYM q_s11_syn FOR q_s11_emp;
                CREATE TYPE q_s11_t AS OBJECT (a NUMBER, b VARCHAR2(10));
                /
                CREATE PROCEDURE q_s11_p (a IN NUMBER, b OUT VARCHAR2, c IN OUT NUMBER, d OUT SYS_REFCURSOR, e IN DATE DEFAULT SYSDATE) AS
                  n NUMBER;
                BEGIN
                  SELECT COUNT(*) INTO n FROM q_s11_emp;
                  b := 'got ' || a || ' on ' || TO_CHAR(e, 'YYYY-MM-DD');
                  c := c * 2 + q_s11_seq.NEXTVAL * 0;
                  OPEN d FOR SELECT id, name FROM q_s11_dept ORDER BY id;
                END;
                /
                CREATE FUNCTION q_s11_f (x NUMBER) RETURN NUMBER AS BEGIN RETURN x + 1; END;
                /
                CREATE FUNCTION q_s11_fb RETURN BOOLEAN AS BEGIN RETURN TRUE; END;
                /
                CREATE FUNCTION q_s11_fc (c IN CHAR, n IN NCHAR) RETURN VARCHAR2 AS BEGIN RETURN c || '|' || n; END;
                /
                CREATE TRIGGER q_s11_trg BEFORE INSERT ON q_s11_emp FOR EACH ROW BEGIN :NEW.name := TRIM(:NEW.name); END;
                /
                CREATE MATERIALIZED VIEW q_s11_mv AS SELECT id, name FROM q_s11_dept;
                INSERT INTO q_s11_dept VALUES (1, 'Sales');
                INSERT INTO q_s11_dept VALUES (2, 'Ops');
                COMMIT;
                BEGIN DBMS_DDL.CREATE_WRAPPED('CREATE PROCEDURE q_s11_wrapped AS BEGIN NULL; END;'); END;
                /
                """);
            _made = true;
        }
        finally { Once.Release(); }
    }

    static ObjectRef Ref(string name, ObjectKind kind) => new() { Schema = Schema, Name = name, Kind = kind };

    static async Task<string?> StatusAsync(DbConnection c, string name, string type) =>
        (string?)await ScalarAsync(c, $"SELECT status FROM user_objects WHERE object_name = '{name}' AND object_type = '{type}'");

