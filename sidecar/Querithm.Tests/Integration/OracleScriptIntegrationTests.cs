    [IntegrationFact]
    public async Task Dependencies_are_what_the_server_recorded_both_ways_without_Oracles_own_objects()
    {
        await SchemaAsync();
        await using var c = await OpenAsync();
        var meta = new OracleMetadata();
        var view = await meta.GetDependenciesAsync(c, Ref("Q_S11_V", ObjectKind.View), Timeout());
        Assert.Contains(view, d => d.Direction == DependencyDirection.Uses && d.Object.Name == "Q_S11_DEPT" && d.Object.Kind == ObjectKind.Table && d.Object.ObjectId != null);
        Assert.Contains(view, d => d.Direction == DependencyDirection.Uses && d.Object.Name == "Q_S11_EMP");
        var emp = await meta.GetDependenciesAsync(c, Ref("Q_S11_EMP", ObjectKind.Table), Timeout());
        Assert.Contains(emp, d => d.Direction == DependencyDirection.UsedBy && d.Object.Name == "Q_S11_V" && d.Object.Kind == ObjectKind.View);
        Assert.Contains(emp, d => d.Direction == DependencyDirection.UsedBy && d.Object.Name == "Q_S11_TRG" && d.Object.Kind == ObjectKind.Trigger);
        Assert.Contains(emp, d => d.Direction == DependencyDirection.UsedBy && d.Object.Name == "Q_S11_P" && d.Object.Kind == ObjectKind.Proc);
        Assert.Contains(emp, d => d.Direction == DependencyDirection.UsedBy && d.Object.Name == "Q_S11_SYN" && d.Object.Kind == ObjectKind.Synonym);
        var proc = await meta.GetDependenciesAsync(c, Ref("Q_S11_P", ObjectKind.Proc), Timeout());
        Assert.Contains(proc, d => d.Direction == DependencyDirection.Uses && d.Object.Name == "Q_S11_SEQ" && d.Object.Kind == ObjectKind.Sequence);
        Assert.DoesNotContain(proc, d => d.Object.Schema is "SYS" or "PUBLIC");
        Assert.DoesNotContain(view.Concat(emp).Concat(proc), d => d.Object.Schema == "SYS");
        // A materialized view does not list its own container table.
        var mv = await meta.GetDependenciesAsync(c, Ref("Q_S11_MV", ObjectKind.View), Timeout());
        Assert.DoesNotContain(mv, d => d.Object.Name == "Q_S11_MV");
        Assert.Contains(mv, d => d.Direction == DependencyDirection.Uses && d.Object.Name == "Q_S11_DEPT");
    }

    [IntegrationFact]
    public async Task Batch_definitions_name_view_columns_qualify_units_and_leave_wrapped_source_out()
    {
        await SchemaAsync();
        await using var c = await OpenAsync();
        var ids = new Dictionary<string, long>();
        await using (var cmd = c.CreateCommand())
        {
            cmd.CommandText = "SELECT object_name, object_id FROM user_objects WHERE object_name IN ('Q_S11_V', 'Q_S11_P', 'Q_S11_TRG', 'Q_S11_WRAPPED') AND object_type IN ('VIEW', 'PROCEDURE', 'TRIGGER')";
            await using var r = await cmd.ExecuteReaderAsync(Timeout());
            while (await r.ReadAsync(Timeout())) ids[r.GetString(0)] = Convert.ToInt64(r.GetValue(1));
        }
        var defs = (await new OracleMetadata().GetDefinitionsAsync(c, ids.Values.ToList(), Timeout())).ToDictionary(d => d.Id, d => d.Definition);
        Assert.StartsWith("CREATE OR REPLACE VIEW QUERITHM_APP.Q_S11_V (DEPT, PEOPLE) AS\n", defs[ids["Q_S11_V"]]);
        Assert.StartsWith("CREATE OR REPLACE PROCEDURE QUERITHM_APP.Q_S11_P", defs[ids["Q_S11_P"]]);
        Assert.EndsWith("\n/", defs[ids["Q_S11_P"]]);
        Assert.Contains("ON q_s11_emp", defs[ids["Q_S11_TRG"]]);
        Assert.True(defs.ContainsKey(ids["Q_S11_WRAPPED"]));
        Assert.Null(defs[ids["Q_S11_WRAPPED"]]);
        // Each definition runs unchanged.
        await RunScriptAsync(c, defs[ids["Q_S11_V"]]!);
        await RunScriptAsync(c, defs[ids["Q_S11_P"]]!);
        Assert.Equal("VALID", await StatusAsync(c, "Q_S11_P", "PROCEDURE"));
    }
