    [IntegrationTheory]
    [InlineData("Q_S11_V", ObjectKind.View, "VIEW")]
    [InlineData("Q_S11_P", ObjectKind.Proc, "PROCEDURE")]
    [InlineData("Q_S11_F", ObjectKind.Func, "FUNCTION")]
    [InlineData("Q_S11_TRG", ObjectKind.Trigger, "TRIGGER")]
    [InlineData("Q_S11_SYN", ObjectKind.Synonym, "SYNONYM")]
    public async Task ALTER_is_CREATE_OR_REPLACE_and_DROP_and_CREATE_runs_unchanged(string name, ObjectKind kind, string type)
    {
        await SchemaAsync();
        await using var c = await OpenAsync();
        var s = new OracleScripter(new OracleMetadata());
        var alter = await s.ScriptAsync(c, Ref(name, kind), ScriptKind.Alter, Timeout());
        Assert.Contains("CREATE OR REPLACE", alter);
        await RunScriptAsync(c, alter);
        Assert.Equal("VALID", await StatusAsync(c, name, type));
        var dropCreate = await s.ScriptAsync(c, Ref(name, kind), ScriptKind.DropCreate, Timeout());
        Assert.StartsWith($"DROP {type} ", dropCreate);
        await RunScriptAsync(c, dropCreate);
        Assert.Equal("VALID", await StatusAsync(c, name, type));
    }

    [IntegrationFact]
    public async Task A_table_a_sequence_and_a_type_script_as_CREATE_that_runs_and_refuse_ALTER_with_the_reason()
    {
        await SchemaAsync();
        await using var c = await OpenAsync();
        var s = new OracleScripter(new OracleMetadata());
        var table = await s.ScriptAsync(c, Ref("Q_S11_EMP", ObjectKind.Table), ScriptKind.Create, Timeout());
        Assert.Contains("CREATE TABLE \"QUERITHM_APP\".\"Q_S11_EMP\"", table);
        Assert.Contains("GENERATED BY DEFAULT", table);
        Assert.DoesNotContain("TABLESPACE", table);
        var seq = await s.ScriptAsync(c, Ref("Q_S11_SEQ", ObjectKind.Sequence), ScriptKind.DropCreate, Timeout());
        await RunScriptAsync(c, seq);
        Assert.Equal("VALID", await StatusAsync(c, "Q_S11_SEQ", "SEQUENCE"));
        var type = await s.ScriptAsync(c, Ref("Q_S11_T", ObjectKind.Type), ScriptKind.Alter, Timeout());
        Assert.Contains("CREATE OR REPLACE", type);
        await RunScriptAsync(c, type);
        Assert.Equal(OracleScripter.NoReplaceTable, (await Assert.ThrowsAsync<NotSupportedException>(() => s.ScriptAsync(c, Ref("Q_S11_EMP", ObjectKind.Table), ScriptKind.Alter, Timeout()))).Message);
        Assert.Equal(OracleScripter.NoReplaceSequence, (await Assert.ThrowsAsync<NotSupportedException>(() => s.ScriptAsync(c, Ref("Q_S11_SEQ", ObjectKind.Sequence), ScriptKind.Alter, Timeout()))).Message);
        // The table's own script, run into an empty copy of the schema, is not tried: it would need the FK's table (covered by compare).
    }

