using System.Data.Common;
using Querithm.Contract;
using Querithm.Contract.Providers;
using Querithm.Core.Compare;
using Querithm.Providers.Oracle;
using static Querithm.Tests.Integration.OracleScriptIntegrationTests;

namespace Querithm.Tests.Integration;

/// <summary>
/// D4 S11 schema compare against the Oracle Free fixture (QUERITHM_IT=1). The round trip: the S11 objects in state A are
/// read as a model, changed to state B, compared A → B, the migration run statement by statement (Oracle commits each),
/// and a second compare of A with the result finds every object identical. Also: what is not compared is listed, and a
/// live compare through the sidecar.
/// </summary>
public sealed class OracleSchemaCompareTests
{
    const string Schema = "QUERITHM_APP";
    const string Prefix = "Q_S11C_";

    static readonly OracleSchemaCompare Dialect = new();

    static readonly (string Kind, string Name)[] Objects =
    [
        ("TRIGGER", "q_s11c_trg"), ("TRIGGER", "q_s11c_trg2"), ("VIEW", "q_s11c_v"), ("VIEW", "q_s11c_v2"), ("PROCEDURE", "q_s11c_p"), ("FUNCTION", "q_s11c_f"),
        ("FUNCTION", "q_s11c_f2"), ("SEQUENCE", "q_s11c_seq"), ("SEQUENCE", "q_s11c_seq2"), ("TABLE", "q_s11c_line"), ("TABLE", "q_s11c_order"),
        ("TABLE", "q_s11c_extra"), ("TABLE", "q_s11c_new"),
    ];

    static async Task DropAllAsync(DbConnection c)
    {
        foreach (var (k, n) in Objects) await DropAsync(c, k, n);
    }

    const string StateA = """
        CREATE TABLE q_s11c_order (
          id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
          code VARCHAR2(20 CHAR) NOT NULL,
          note VARCHAR2(200 BYTE) DEFAULT 'none',
          status CHAR(1) DEFAULT 'N' NOT NULL,
          amount NUMBER(12,2) DEFAULT 0,
          placed DATE DEFAULT SYSDATE,
          at TIMESTAMP(3) WITH TIME ZONE,
          raw_id RAW(16),
          code_upper GENERATED ALWAYS AS (UPPER(code)) VIRTUAL,
          CONSTRAINT q_s11c_order_pk PRIMARY KEY (id),
          CONSTRAINT q_s11c_order_code_uk UNIQUE (code),
          CONSTRAINT q_s11c_order_status_ck CHECK (status IN ('N', 'P', 'X')),
          CHECK (amount >= 0));
        CREATE INDEX q_s11c_order_placed_ix ON q_s11c_order (placed DESC, amount);
        CREATE INDEX q_s11c_order_lower_ix ON q_s11c_order (LOWER(note));
        CREATE TABLE q_s11c_line (
          order_id NUMBER(10) NOT NULL,
          line_no NUMBER(4) NOT NULL,
          qty NUMBER DEFAULT ON NULL 1,
          CONSTRAINT q_s11c_line_pk PRIMARY KEY (order_id, line_no),
          CONSTRAINT q_s11c_line_order_fk FOREIGN KEY (order_id) REFERENCES q_s11c_order (id) ON DELETE CASCADE);
        CREATE TABLE q_s11c_extra (id NUMBER PRIMARY KEY, label VARCHAR2(10));
        CREATE SEQUENCE q_s11c_seq START WITH 10 INCREMENT BY 5 MAXVALUE 100000 NOCYCLE;
        CREATE SEQUENCE q_s11c_seq2;
        CREATE VIEW q_s11c_v (code, lines) AS SELECT o.code, COUNT(l.line_no) FROM q_s11c_order o LEFT JOIN q_s11c_line l ON l.order_id = o.id GROUP BY o.code;
        CREATE VIEW q_s11c_v2 AS SELECT code FROM q_s11c_v WHERE lines > 1;
        CREATE FUNCTION q_s11c_f (p_id NUMBER) RETURN NUMBER AS
          n NUMBER;
        BEGIN
          SELECT COUNT(*) INTO n FROM q_s11c_line WHERE order_id = p_id;
          RETURN n;
        END;
        /
        CREATE FUNCTION q_s11c_f2 RETURN NUMBER AS BEGIN RETURN q_s11c_seq.NEXTVAL; END;
        /
        CREATE PROCEDURE q_s11c_p (p_code IN VARCHAR2) AS
        BEGIN
          UPDATE q_s11c_order SET status = 'P' WHERE code = p_code;
        END;
        /
        CREATE TRIGGER q_s11c_trg BEFORE INSERT ON q_s11c_order FOR EACH ROW
        BEGIN
          :NEW.code := TRIM(:NEW.code);
        END;
        /
        """;

    /// <summary>State B: what a target drifted to — every kind of change the migration has to undo.</summary>
    const string ToStateB = """
        DROP TRIGGER q_s11c_trg;
        CREATE TRIGGER q_s11c_trg2 BEFORE UPDATE ON q_s11c_line FOR EACH ROW BEGIN :NEW.qty := NVL(:NEW.qty, 0); END;
        /
        ALTER TABLE q_s11c_order DROP CONSTRAINT q_s11c_order_status_ck;
        ALTER TABLE q_s11c_order ADD CONSTRAINT q_s11c_order_status_ck CHECK (status IN ('N', 'P'));
        ALTER TABLE q_s11c_order DROP COLUMN raw_id;
        ALTER TABLE q_s11c_order ADD (extra_col NUMBER(3));
        DROP INDEX q_s11c_order_lower_ix;
        ALTER TABLE q_s11c_order MODIFY (note VARCHAR2(100 BYTE) DEFAULT NULL);
        ALTER TABLE q_s11c_order MODIFY (amount DEFAULT 1);
        ALTER TABLE q_s11c_order MODIFY (placed NOT NULL);
        CREATE INDEX q_s11c_order_lower_ix ON q_s11c_order (UPPER(note));
        ALTER TABLE q_s11c_line DROP CONSTRAINT q_s11c_line_order_fk;
        ALTER TABLE q_s11c_line ADD CONSTRAINT q_s11c_line_order_fk FOREIGN KEY (order_id) REFERENCES q_s11c_order (id);
        DROP TABLE q_s11c_extra PURGE;
        CREATE TABLE q_s11c_new (id NUMBER PRIMARY KEY);
        ALTER SEQUENCE q_s11c_seq INCREMENT BY 1;
        DROP SEQUENCE q_s11c_seq2;
        CREATE OR REPLACE VIEW q_s11c_v (code, lines) AS SELECT o.code, COUNT(*) FROM q_s11c_order o JOIN q_s11c_line l ON l.order_id = o.id GROUP BY o.code;
        DROP FUNCTION q_s11c_f2;
        CREATE OR REPLACE PROCEDURE q_s11c_p (p_code IN VARCHAR2) AS
        BEGIN
          UPDATE q_s11c_order SET status = 'X' WHERE code = p_code;
        END;
        /
        CREATE OR REPLACE FUNCTION q_s11c_f (p_id NUMBER) RETURN NUMBER AS
          n NUMBER;
        BEGIN
          SELECT COUNT(*) INTO n FROM q_s11c_line WHERE order_id = p_id;
          RETURN   n;
        END;
        /
        """;

    /// <summary>The model restricted to the S11 compare objects (other tests own the rest of the schema).</summary>
    static SchemaModel Ours(SchemaModel m) => m with
    {
        Schemas = [Schema],
        Tables = m.Tables.Where(t => t.Schema == Schema && t.Name.StartsWith(Prefix, StringComparison.Ordinal)).ToArray(),
        Modules = m.Modules.Where(x => x.Schema == Schema && x.Name.StartsWith(Prefix, StringComparison.Ordinal)).ToArray(),
        Sequences = m.Sequences.Where(x => x.Schema == Schema && x.Name.StartsWith(Prefix, StringComparison.Ordinal)).ToArray(),
    };

    static async Task<SchemaModel> ReadAsync(DbConnection c) => Ours(await Dialect.ReadModelAsync(c, Timeout(300)));

    static string Describe(Comparison cmp) =>
        string.Join("\n", cmp.Items.Where(i => i.Class != CompareClass.Identical).Select(i => $"{i.Kind} {i.Schema}.{i.Name} {i.Class}: {string.Join("; ", i.Changes)} {i.Note}"));

    [IntegrationFact]
    public async Task Compare_migrate_and_compare_again_is_identical()
    {
        await using var c = await OpenAsync();
        await DropAllAsync(c);
        await RunScriptAsync(c, StateA);
        var a = await ReadAsync(c);
        Assert.Equal(3, a.Tables.Length); // order, line, extra
        var order = Assert.Single(a.Tables, t => t.Name == "Q_S11C_ORDER");
        Assert.Equal("NUMBER(10)", order.Columns.Single(x => x.Name == "ID").Type);
        Assert.Equal("BY DEFAULT", order.Columns.Single(x => x.Name == "ID").Identity);
        Assert.Equal("VARCHAR2(20 CHAR)", order.Columns.Single(x => x.Name == "CODE").Type);
        Assert.Equal("UPPER(\"CODE\")", order.Columns.Single(x => x.Name == "CODE_UPPER").Computed);
        Assert.Equal("ON NULL 1", Assert.Single(a.Tables, t => t.Name == "Q_S11C_LINE").Columns.Single(x => x.Name == "QTY").Default);
        Assert.DoesNotContain(order.Checks, k => k.Expression.Contains("IS NOT NULL", StringComparison.Ordinal)); // NOT NULL is the column's
        Assert.Contains(order.Checks, k => k.SystemNamed);
        var placed = Assert.Single(order.Indexes, i => i.Name == "Q_S11C_ORDER_PLACED_IX");
        Assert.Equal(["PLACED", "AMOUNT"], placed.Columns);
        Assert.Equal([true, false], placed.Descending!);
        Assert.Contains("LOWER(\"NOTE\")", Assert.Single(order.Indexes, i => i.Name == "Q_S11C_ORDER_LOWER_IX").Columns);
        Assert.DoesNotContain(order.Indexes, i => i.Name == "Q_S11C_ORDER_PK"); // the key's own index comes with the key
        Assert.Contains(a.Modules, m => m.Name == "Q_S11C_V2" && m.References.Any(r => r.Name == "Q_S11C_V"));

        await RunScriptAsync(c, ToStateB);
        var b = await ReadAsync(c);
        var cmp = SchemaComparer.Compare(a, b, Dialect);
        Assert.NotEqual("", Describe(cmp));
        var keys = cmp.Items.Where(i => i.Class != CompareClass.Identical).Select(i => i.Key).ToList();
        var migration = new MigrationScriptBuilder(cmp).Build(keys, [], includeDataLoss: true, "-- test migration");
        Assert.False(migration.Transactional);
        Assert.Contains("not one transaction", migration.Sql);
        Assert.DoesNotContain(migration.Warnings, w => !w.Contains("NOT NULL", StringComparison.Ordinal));
        await RunScriptAsync(c, migration.Sql);

        var after = await ReadAsync(c);
        var again = SchemaComparer.Compare(a, after, Dialect);
        Assert.True(again.Items.All(i => i.Class == CompareClass.Identical), "Still different after the migration:\n" + Describe(again) + "\n\nMigration:\n" + migration.Sql);
        // The migrated objects work.
        Assert.Equal(0m, Convert.ToDecimal(await ScalarAsync(c, "SELECT q_s11c_f(1) FROM dual")));
        Assert.Equal("VALID", await ScalarAsync(c, "SELECT status FROM user_objects WHERE object_name = 'Q_S11C_V2' AND object_type = 'VIEW'"));
        await DropAllAsync(c);
    }

    [IntegrationFact]
    public async Task What_is_not_compared_is_listed_with_the_reason()
    {
        await using var c = await OpenAsync();
        var m = await Dialect.ReadModelAsync(c, Timeout(300));
        Assert.Contains(Schema, m.Schemas);
        Assert.DoesNotContain("SYS", m.Schemas);
        Assert.Contains(m.NotCompared, n => n.Contains("not compared", StringComparison.Ordinal) && n.Contains("grants", StringComparison.Ordinal));
        // The package and materialized-view fixtures of S08 / S05 / S11 are counted, never modelled.
        await RunScriptAsync(c, "BEGIN EXECUTE IMMEDIATE 'CREATE OR REPLACE PACKAGE q_s11c_pkg AS PROCEDURE p; END;'; END;\n/");
        m = await Dialect.ReadModelAsync(c, Timeout(300));
        Assert.Contains(m.NotCompared, n => n.Contains("package(s) are not compared", StringComparison.Ordinal));
        Assert.DoesNotContain(m.Modules, x => x.Name == "Q_S11C_PKG");
        await DropAsync(c, "PACKAGE", "q_s11c_pkg");
    }

    [IntegrationFact]
    public async Task A_live_compare_through_the_sidecar_and_its_migration_script()
    {
        await using (var c = await OpenAsync())
        {
            await DropAllAsync(c);
            await RunScriptAsync(c, StateA);
        }
        await using var h = await OracleS11Host.OpenAsync(refresh: false);
        Assert.True((await h.Rpc.SessionCapabilities(new SessionRef { SessionId = h.Sid })).SchemaCompare.Available);
        var side = new CompareSide { SessionId = h.Sid, Database = OracleS11Host.Db, Schema = Schema };
        var r = await h.Rpc.SchemaCompareRun(new SchemaCompareParams { Source = side, Target = side });
        Assert.True(r.Items.All(i => i.Class == CompareClass.Identical));
        Assert.False(r.TransactionalDdl);
        Assert.Contains(r.Notes, n => n.Contains("not compared", StringComparison.Ordinal));
        var item = r.Items.First(i => i.Kind == CompareObjectKind.Table && i.Name == "Q_S11C_ORDER");
        var sql = await h.Rpc.SchemaCompareObjectSql(new CompareObjectParams { CompareId = r.CompareId, Key = item.Key });
        Assert.Contains("CREATE TABLE \"QUERITHM_APP\".\"Q_S11C_ORDER\"", sql.Source);
        await using (var c = await OpenAsync()) await DropAllAsync(c);
    }
}
