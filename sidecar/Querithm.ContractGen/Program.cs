// Emits src/ipc/contract.ts from Querithm.Contract (§5). Usage: ContractGen <output-path>
using System.Reflection;
using System.Text;
using System.Text.Json;
using Querithm.Contract;

var output = args.Length > 0 ? args[0] : Path.Combine("..", "src", "ipc", "contract.ts");
var asm = typeof(ContractInfo).Assembly;
var nullability = new NullabilityInfoContext();
string Camel(string s) => JsonNamingPolicy.CamelCase.ConvertName(s);

var types = asm.GetExportedTypes()
    .Where(t => t.Namespace == "Querithm.Contract")
    .Where(t => !t.IsInterface && !typeof(Attribute).IsAssignableFrom(t) && !(t.IsAbstract && t.IsSealed))
    .OrderBy(t => t.IsEnum ? 0 : 1).ThenBy(t => t.Name, StringComparer.Ordinal)
    .ToList();

string TsType(Type t, NullabilityInfo? info = null)
{
    var under = Nullable.GetUnderlyingType(t);
    if (under != null) return TsType(under);
    if (t == typeof(string)) return "string";
    if (t == typeof(bool)) return "boolean";
    if (t == typeof(int) || t == typeof(long) || t == typeof(double) || t == typeof(float) || t == typeof(decimal) || t == typeof(short) || t == typeof(byte))
        return "number";
    if (t.IsArray)
    {
        var el = TsType(t.GetElementType()!, info?.ElementType);
        return el.Contains(' ') ? $"({el})[]" : $"{el}[]";
    }
    if (t.IsGenericType && t.GetGenericTypeDefinition() == typeof(Dictionary<,>))
        return $"Record<{TsType(t.GetGenericArguments()[0])}, {TsType(t.GetGenericArguments()[1], info?.GenericTypeArguments[1])}>";
    if (t.IsGenericType && t.GetGenericTypeDefinition() == typeof(List<>))
        return $"{TsType(t.GetGenericArguments()[0])}[]";
    if (t.Namespace == "Querithm.Contract") return t.Name;
    throw new InvalidOperationException($"No TS mapping for {t.FullName}");
}

var sb = new StringBuilder();
sb.AppendLine("// GENERATED by scripts/gen-contract from sidecar/Querithm.Contract. Do not edit by hand (§15 rule 5).");
sb.AppendLine("/* eslint-disable */");
sb.AppendLine();
sb.AppendLine($"export const CONTRACT_VERSION = \"{ContractInfo.Version}\";");
sb.AppendLine();

foreach (var t in types)
{
    if (t.IsEnum)
    {
        var names = Enum.GetNames(t).Select(n => $"\"{Camel(n)}\"");
        sb.AppendLine($"export type {t.Name} = {string.Join(" | ", names)};");
        sb.AppendLine($"export const {t.Name}Values = [{string.Join(", ", names)}] as const;");
        continue;
    }
    var props = t.GetProperties(BindingFlags.Public | BindingFlags.Instance)
        .Where(p => p.Name != "EqualityContract")
        .ToList();
    if (props.Count == 0)
    {
        sb.AppendLine($"export type {t.Name} = Record<string, never>;");
        continue;
    }
    sb.AppendLine($"export interface {t.Name} {{");
    foreach (var p in props)
    {
        var info = nullability.Create(p);
        var isNullable = Nullable.GetUnderlyingType(p.PropertyType) != null
                         || (!p.PropertyType.IsValueType && info.ReadState == NullabilityState.Nullable);
        var doc = p.GetCustomAttribute<System.ComponentModel.DescriptionAttribute>()?.Description;
        if (doc != null) sb.AppendLine($"  /** {doc} */");
        sb.AppendLine($"  {Camel(p.Name)}{(isNullable ? "?" : "")}: {TsType(p.PropertyType, info)}{(isNullable ? " | null" : "")};");
    }
    sb.AppendLine("}");
}

sb.AppendLine();
sb.AppendLine("/** Control-plane methods: params and result per JSON-RPC method name. */");
sb.AppendLine("export interface RpcMap {");
foreach (var m in typeof(IQuerithmRpc).GetMethods())
{
    var attr = m.GetCustomAttribute<RpcMethodAttribute>() ?? throw new InvalidOperationException(m.Name);
    var ps = m.GetParameters();
    var param = ps.Length == 0 ? "void" : TsType(ps[0].ParameterType);
    var ret = m.ReturnType == typeof(Task) ? "void" : TsType(m.ReturnType.GetGenericArguments()[0]);
    sb.AppendLine($"  \"{attr.Name}\": {{ params: {param}; result: {ret} }};");
}
sb.AppendLine("}");
sb.AppendLine("export type RpcMethod = keyof RpcMap;");
sb.AppendLine();
sb.AppendLine("/** Sidecar → webview notifications: payload per method name. */");
sb.AppendLine("export interface NotificationMap {");
foreach (var m in typeof(IQuerithmNotifications).GetMethods())
{
    var attr = m.GetCustomAttribute<RpcNotificationAttribute>() ?? throw new InvalidOperationException(m.Name);
    sb.AppendLine($"  \"{attr.Name}\": {TsType(m.GetParameters()[0].ParameterType)};");
}
sb.AppendLine("}");
sb.AppendLine("export type NotificationMethod = keyof NotificationMap;");

Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(output))!);
var text = sb.ToString().Replace("\r\n", "\n");
if (!File.Exists(output) || File.ReadAllText(output) != text)
{
    File.WriteAllText(output, text);
    Console.WriteLine($"wrote {output}");
}
else Console.WriteLine($"{output} is up to date");
