#!/usr/bin/env node
// THIRD-PARTY-NOTICES.md (§13 rule 11): every shipped npm package, NuGet package and Rust crate with its license.
// Works offline: reads node_modules, the NuGet global packages folder and `cargo metadata --offline`.
// SMO's license text is included verbatim; its redistribution terms must be confirmed before a public release.
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lines = ["# Third-party notices", "", "Generated by `scripts/gen-notices.mjs`. Querithm itself is MIT licensed.", ""];
const verbatim = [];

// ---- npm (production dependencies bundled into the webview) ----
const npm = new Map();
function walk(dir, depth = 0) {
  const pkg = path.join(dir, "package.json");
  if (!existsSync(pkg)) return;
  const j = JSON.parse(readFileSync(pkg, "utf8"));
  const key = `${j.name}@${j.version}`;
  if (npm.has(key)) return;
  const license = typeof j.license === "string" ? j.license : j.license?.type ?? (Array.isArray(j.licenses) ? j.licenses.map((l) => l.type).join(" OR ") : "UNKNOWN");
  npm.set(key, { name: j.name, version: j.version, license, homepage: j.homepage ?? "" });
  for (const dep of Object.keys(j.dependencies ?? {})) {
    const candidates = [path.join(dir, "node_modules", dep), path.join(dir, "..", dep), path.join(root, "node_modules", dep)];
    const d = candidates.find((c) => existsSync(path.join(c, "package.json")));
    if (d && depth < 30) walk(fsReal(d), depth + 1);
  }
}
function fsReal(p) {
  try {
    return execFileSync("realpath", [p]).toString().trim();
  } catch {
    return p;
  }
}
const rootPkg = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
for (const dep of Object.keys(rootPkg.dependencies ?? {})) walk(fsReal(path.join(root, "node_modules", dep)));
lines.push("## Webview (npm)", "", "| Package | Version | License |", "|---|---|---|");
for (const p of [...npm.values()].sort((a, b) => a.name.localeCompare(b.name))) lines.push(`| ${p.name} | ${p.version} | ${p.license} |`);
lines.push("");

// ---- NuGet (sidecar) ----
const assets = path.join(root, "sidecar", "Querithm.Host", "obj", "project.assets.json");
const nugetRoot = process.env.NUGET_PACKAGES ?? path.join(os.homedir(), ".nuget", "packages");
lines.push("## Engine (.NET sidecar, NuGet)", "", "| Package | Version | License |", "|---|---|---|");
if (existsSync(assets)) {
  const libs = JSON.parse(readFileSync(assets, "utf8")).libraries;
  const rows = [];
  for (const [id, info] of Object.entries(libs)) {
    if (info.type !== "package") continue;
    const [name, version] = id.split("/");
    const dir = path.join(nugetRoot, name.toLowerCase(), version.toLowerCase());
    const nuspec = existsSync(dir) ? readdirSync(dir).find((f) => f.endsWith(".nuspec")) : undefined;
    let license = "see package";
    if (nuspec) {
      const x = readFileSync(path.join(dir, nuspec), "utf8");
      const expr = /<license type="expression">([^<]+)<\/license>/.exec(x)?.[1];
      const file = /<license type="file">([^<]+)<\/license>/.exec(x)?.[1];
      const url = /<licenseUrl>([^<]+)<\/licenseUrl>/.exec(x)?.[1];
      license = expr ?? (file ? `file: ${file}` : url ?? "see package");
      if (file && /SqlManagementObjects|Smo|Sfc|ConnectionInfo/i.test(name) && existsSync(path.join(dir, file)))
        verbatim.push({ title: `${name} ${version}`, text: readFileSync(path.join(dir, file), "utf8") });
      // Phase D4: ODP.NET is redistributed under the Oracle Free Distribution, Hosting, and Use Terms, which require a
      // copy of the license with every distribution, and its info.txt carries the third-party notices (MIT Kerberos and
      // others) that must be kept. Both verbatim.
      if (name === "Oracle.ManagedDataAccess.Core") {
        for (const f of [file, "info.txt"].filter(Boolean)) {
          const p = path.join(dir, f);
          if (!existsSync(p)) throw new Error(`${name} ${version}: ${f} is missing from the package; its notices must ship`);
          verbatim.push({ title: `${name} ${version} — ${f}`, text: readFileSync(p, "utf8").replace(/^﻿/, "") });
        }
      }
    }
    rows.push(`| ${name} | ${version} | ${license} |`);
  }
  lines.push(...rows.sort());
} else lines.push("| (run `dotnet restore sidecar` first) | | |");
lines.push("");

// ---- Rust crates (shell) ----
// Native code inside NuGet packages whose metadata names only the wrapper's license (Phase D per-engine checklist).
lines.push(
  "## Native libraries bundled in the engine",
  "",
  "| Library | Shipped in | License |",
  "|---|---|---|",
  "| SQLite 3.53.3 (e_sqlite3) | SQLitePCLRaw.lib.e_sqlite3 2.1.13 | Public domain (https://sqlite.org/copyright.html) |",
  "| DuckDB 1.5.6 (libduckdb, with its built-in extensions) | DuckDB.NET.Bindings.Full 1.5.6.1 | MIT, Copyright 2018-2022 Stichting DuckDB Foundation (LICENSE-DuckDB.txt in the package) |",
  "",
);

lines.push("## Shell (Rust crates)", "", "| Crate | Version | License |", "|---|---|---|");
try {
  const meta = JSON.parse(execFileSync("cargo", ["metadata", "--format-version", "1", "--offline", "--manifest-path", path.join(root, "src-tauri", "Cargo.toml")], { maxBuffer: 1 << 28 }).toString());
  for (const p of meta.packages.filter((p) => p.name !== "querithm").sort((a, b) => a.name.localeCompare(b.name)))
    lines.push(`| ${p.name} | ${p.version} | ${p.license ?? (p.license_file ? "file" : "UNKNOWN")} |`);
} catch (e) {
  lines.push(`| (cargo metadata failed: ${String(e.message).split("\n")[0]}) | | |`);
}
lines.push("");

if (verbatim.length) {
  lines.push("## License texts included verbatim", "");
  for (const v of verbatim) lines.push(`### ${v.title}`, "", "```", v.text.trim(), "```", "");
}
writeFileSync(path.join(root, "THIRD-PARTY-NOTICES.md"), lines.join("\n"));
console.log(`THIRD-PARTY-NOTICES.md: ${npm.size} npm packages, NuGet + crates, ${verbatim.length} verbatim license(s)`);
