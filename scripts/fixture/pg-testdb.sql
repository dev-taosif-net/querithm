CREATE TABLE sales.order_lines (
    order_id    bigint NOT NULL,
    ordered_at  timestamptz NOT NULL,
    line_no     smallint NOT NULL,
    product_id  integer NOT NULL REFERENCES inventory.products,
    quantity    integer NOT NULL CHECK (quantity > 0),
    unit_price  numeric(12, 2) NOT NULL,
    discount    numeric(4, 3) NOT NULL DEFAULT 0 CHECK (discount BETWEEN 0 AND 1),
    line_total  numeric(14, 2) GENERATED ALWAYS AS (round(quantity * unit_price * (1 - discount), 2)) STORED,
    PRIMARY KEY (order_id, line_no),
    FOREIGN KEY (order_id, ordered_at) REFERENCES sales.orders (order_id, ordered_at) ON DELETE CASCADE
);
