-- ─── Functions, procedures, triggers ──────────────────────────────────────────────────────────────────────────
CREATE FUNCTION audit.touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END $$;

CREATE FUNCTION audit.log_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO audit.row_changes (table_name, operation, old_row, new_row)
    VALUES (TG_RELID, left(TG_OP, 1),
            CASE WHEN TG_OP <> 'INSERT' THEN to_jsonb(OLD) END,
            CASE WHEN TG_OP <> 'DELETE' THEN to_jsonb(NEW) END);
    RETURN COALESCE(NEW, OLD);
END $$;

CREATE TRIGGER employees_touch BEFORE UPDATE ON hr.employees FOR EACH ROW EXECUTE FUNCTION audit.touch_updated_at();
CREATE TRIGGER products_touch BEFORE UPDATE ON inventory.products FOR EACH ROW EXECUTE FUNCTION audit.touch_updated_at();
CREATE TRIGGER products_audit AFTER INSERT OR UPDATE OR DELETE ON inventory.products
    FOR EACH ROW EXECUTE FUNCTION audit.log_change();

CREATE FUNCTION sales.order_total(p_order_id bigint) RETURNS numeric LANGUAGE sql STABLE AS $$
    SELECT coalesce(sum(line_total), 0) FROM sales.order_lines WHERE order_id = p_order_id
$$;
COMMENT ON FUNCTION sales.order_total(bigint) IS 'Sum of line totals for one order';

CREATE FUNCTION sales.customer_stats(p_customer uuid, OUT order_count bigint, OUT lifetime_value numeric, OUT last_order timestamptz)
LANGUAGE sql STABLE AS $$
    SELECT count(*), coalesce(sum(total), 0), max(ordered_at) FROM sales.orders WHERE customer_id = p_customer
$$;

CREATE FUNCTION inventory.low_stock(p_threshold integer DEFAULT 10)
RETURNS TABLE (warehouse varchar, sku char(10), product text, quantity integer)
LANGUAGE sql STABLE AS $$
    SELECT w.code, p.sku, p.name, s.quantity
    FROM inventory.stock s
    JOIN inventory.warehouses w USING (warehouse_id)
    JOIN inventory.products p USING (product_id)
    WHERE s.quantity < p_threshold
    ORDER BY s.quantity, p.sku
$$;

-- Deliberately step-friendly for the PL/pgSQL debugger: loops, branches, locals, RAISE NOTICE.
CREATE FUNCTION sales.loyalty_score(p_customer uuid) RETURNS integer LANGUAGE plpgsql AS $$
DECLARE
    v_score   integer := 0;
    v_order   record;
    v_months  numeric;
BEGIN
    FOR v_order IN SELECT status, total, ordered_at FROM sales.orders WHERE customer_id = p_customer ORDER BY ordered_at LOOP
        IF v_order.status IN ('cancelled', 'refunded') THEN
            v_score := v_score - 5;
        ELSIF v_order.total > 500 THEN
            v_score := v_score + 20;
        ELSE
            v_score := v_score + 5;
        END IF;
    END LOOP;
    v_months := extract(epoch FROM (now() - (SELECT created_at FROM sales.customers WHERE customer_id = p_customer))) / 2629800;
    v_score := v_score + floor(coalesce(v_months, 0))::int;
    RAISE NOTICE 'customer % scored %', p_customer, v_score;
    RETURN greatest(v_score, 0);
END $$;

