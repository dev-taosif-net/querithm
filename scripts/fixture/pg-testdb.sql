-- ─── HR ───────────────────────────────────────────────────────────────────────────────────────────────────────
CREATE TABLE hr.departments (
    department_id  smallint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name           varchar(60) NOT NULL UNIQUE,
    parent_id      smallint REFERENCES hr.departments (department_id),
    budget         money
);

CREATE TABLE hr.employees (
    employee_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name     varchar(40) NOT NULL,
    last_name      varchar(40) NOT NULL,
    full_name      text GENERATED ALWAYS AS (first_name || ' ' || last_name) STORED,
    email          sales.email NOT NULL UNIQUE,
    department_id  smallint NOT NULL REFERENCES hr.departments,
    manager_id     integer REFERENCES hr.employees (employee_id) ON DELETE SET NULL,
    hired_on       date NOT NULL DEFAULT current_date,
    salary         numeric(10, 2) CHECK (salary > 0),
    is_active      boolean NOT NULL DEFAULT true,
    shift_start    time,
    notes          text,
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE hr.employees IS 'Staff; manager_id is a self-reference used by hr.org_chart';
COMMENT ON COLUMN hr.employees.full_name IS 'Generated: first_name || '' '' || last_name';

CREATE TABLE hr.room_bookings (
    booking_id   bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    room         smallint NOT NULL,
    booked_by    integer NOT NULL REFERENCES hr.employees,
    during       tstzrange NOT NULL,
    EXCLUDE USING gist (room WITH =, during WITH &&)
);
COMMENT ON TABLE hr.room_bookings IS 'Exclusion constraint: no overlapping bookings per room';

-- ─── Inventory ────────────────────────────────────────────────────────────────────────────────────────────────
CREATE TABLE inventory.categories (
    category_id  serial PRIMARY KEY,
    name         text NOT NULL UNIQUE,
    slug         text NOT NULL UNIQUE CHECK (slug = lower(slug))
