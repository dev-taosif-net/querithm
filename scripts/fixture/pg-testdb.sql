-- Procedure with COMMIT inside: exercises CALL and transaction-control handling.
CREATE PROCEDURE inventory.restock(p_warehouse smallint, p_amount integer DEFAULT 50)
LANGUAGE plpgsql AS $$
DECLARE
    v_row record;
    v_done integer := 0;
BEGIN
    FOR v_row IN SELECT product_id FROM inventory.stock WHERE warehouse_id = p_warehouse AND quantity < 10 LOOP
        UPDATE inventory.stock SET quantity = quantity + p_amount
        WHERE warehouse_id = p_warehouse AND product_id = v_row.product_id;
        v_done := v_done + 1;
        IF v_done % 20 = 0 THEN
            COMMIT;
        END IF;
    END LOOP;
    RAISE NOTICE 'restocked % products in warehouse %', v_done, p_warehouse;
END $$;

