-- ─── Views ────────────────────────────────────────────────────────────────────────────────────────────────────
CREATE VIEW sales.order_summary AS
SELECT o.order_id, o.ordered_at, o.status, c.display_name AS customer, (c.billing).country AS country,
       count(l.line_no) AS line_count, o.total, e.full_name AS handled_by
FROM sales.orders o
JOIN sales.customers c USING (customer_id)
LEFT JOIN sales.order_lines l USING (order_id)
LEFT JOIN hr.employees e ON e.employee_id = o.handled_by
GROUP BY o.order_id, o.ordered_at, o.status, c.display_name, c.billing, o.total, e.full_name;
COMMENT ON VIEW sales.order_summary IS 'One row per order with customer and line count';

CREATE VIEW hr.org_chart AS
WITH RECURSIVE tree AS (
    SELECT employee_id, full_name, manager_id, 0 AS depth, ARRAY[employee_id] AS path
    FROM hr.employees WHERE manager_id IS NULL
    UNION ALL
    SELECT e.employee_id, e.full_name, e.manager_id, t.depth + 1, t.path || e.employee_id
    FROM hr.employees e JOIN tree t ON e.manager_id = t.employee_id
)
SELECT employee_id, repeat('  ', depth) || full_name AS name, depth, path FROM tree;

CREATE MATERIALIZED VIEW sales.monthly_revenue AS
SELECT date_trunc('month', o.ordered_at) AS month, cat.name AS category,
       sum(l.line_total) AS revenue, count(DISTINCT o.order_id) AS orders
FROM sales.orders o
JOIN sales.order_lines l USING (order_id)
JOIN inventory.products p USING (product_id)
JOIN inventory.categories cat USING (category_id)
WHERE o.status NOT IN ('cancelled', 'refunded')
GROUP BY 1, 2
WITH DATA;
CREATE UNIQUE INDEX monthly_revenue_key ON sales.monthly_revenue (month, category);

